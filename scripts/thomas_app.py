"""Install Thomas as a real desktop app, not a browser tab.

Thomas should open the way Claude Code and Codex do — from a shortcut wearing
his own face, straight into his own window. No tabs, no address bar, no
search engine, no other site's chrome. The browser is an implementation
detail the owner should never see.

What this installs:
  * ``assets/thomas.ico`` — the two-eyes-in-a-block brand mark (regenerated).
  * ``Thomas.vbs`` — a launcher that opens the Thomas desktop shell in
    ``desktop/``: a real browser engine, so web tabs load sites that refuse to
    be framed. The shell attaches to a running engine or starts one itself, so
    the launcher does not need to wait on health.

    Before 2026-09-02 this launcher opened ``msedge --app=http://127.0.0.1:8899``
    instead. That window could only show web tabs in an iframe, and Gmail, Wells
    Fargo and most other sites refuse to be framed - you clicked a bookmark and
    got "This content is blocked". The desktop shell loads them as top-level
    navigations, which those headers do not apply to. The browser path is kept
    only as a fallback for when ``desktop/node_modules`` has not been installed.
  * A ``Thomas`` shortcut on the Desktop and in the Start Menu, pointing at
    that launcher with the icon attached.

Usage:
    python scripts/thomas_app.py                 # install (Desktop + Start Menu)
    python scripts/thomas_app.py --port 8899
    python scripts/thomas_app.py --dry-run
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
ICON = REPO_ROOT / "assets" / "thomas.ico"
APP_VBS = REPO_ROOT / "Thomas.vbs"
DESKTOP_DIR = REPO_ROOT / "desktop"
ELECTRON_EXE = DESKTOP_DIR / "node_modules" / "electron" / "dist" / "electron.exe"
RUN_DESKTOP_PS1 = REPO_ROOT / "scripts" / "run-desktop.ps1"
DEFAULT_PORT = 8899

_LAUNCHER = """Option Explicit
' Thomas — desktop app launcher (generated by scripts/thomas_app.py).
' Opens the Thomas desktop shell: a real browser engine around the Thomas
' chrome, so a web tab can load a site that refuses to be framed.
Dim shell, fso, electronExe, desktopDir, runDesktopPs1, appUrl, profileDir, args, answer

Set shell = CreateObject("WScript.Shell")
Set fso = CreateObject("Scripting.FileSystemObject")
desktopDir = "{desktop_dir}"
electronExe = "{electron_exe}"
runDesktopPs1 = "{run_desktop_ps1}"
appUrl = "http://127.0.0.1:{port}/"

If fso.FileExists(electronExe) Then
    ' The shell attaches to a running engine or spawns one itself, and only
    ' stops the engine it started. Nothing to wait for here.
    shell.CurrentDirectory = desktopDir
    shell.Run Chr(34) & electronExe & Chr(34) & " " & Chr(34) & desktopDir & Chr(34), 1, False
    WScript.Quit 0
End If

' The shell is not built yet - a fresh checkout, or setup was never run.
' run-desktop.ps1 installs the dependencies on first run and then launches, so
' offer that rather than dead-ending in a dialog. Visible window on purpose:
' the install takes a minute and silence reads as nothing happening.
If fso.FileExists(runDesktopPs1) Then
    answer = MsgBox("Thomas needs to finish installing its desktop shell before websites will load in web tabs." & vbCrLf & vbCrLf & _
        "This downloads the browser engine and takes about a minute. It only happens once." & vbCrLf & vbCrLf & _
        "Install it now?", 36, "Thomas")
    If answer = 6 Then
        shell.Run "powershell -NoProfile -ExecutionPolicy Bypass -File " & Chr(34) & runDesktopPs1 & Chr(34), 1, False
        WScript.Quit 0
    End If
End If

' Declined, or the installer script is missing. Thomas still opens, but web
' tabs fall back to iframes and sites that refuse framing will show blank.
profileDir = shell.ExpandEnvironmentStrings("%LOCALAPPDATA%") & "\\Thomas\\AppWindow"
If Not fso.FolderExists(shell.ExpandEnvironmentStrings("%LOCALAPPDATA%") & "\\Thomas") Then
    fso.CreateFolder shell.ExpandEnvironmentStrings("%LOCALAPPDATA%") & "\\Thomas"
End If
args = " --app=" & appUrl & _
       " --user-data-dir=" & Chr(34) & profileDir & Chr(34) & _
       " --window-size=1440,960 --no-first-run --no-default-browser-check"

On Error Resume Next
shell.Run "msedge" & args, 1, False
If Err.Number <> 0 Then
    Err.Clear
    shell.Run "chrome" & args, 1, False
End If
If Err.Number <> 0 Then
    Err.Clear
    shell.Run appUrl, 1, False
End If
"""


_SHORTCUT_PS1 = """$ws = New-Object -ComObject WScript.Shell
$sc = $ws.CreateShortcut('{lnk}')
$sc.TargetPath = '{target}'
$sc.WorkingDirectory = '{workdir}'
$sc.IconLocation = '{icon},0'
$sc.Description = 'Thomas'
$sc.WindowStyle = 1
$sc.Save()
"""


def _run_powershell(script: str) -> tuple[int, str]:
    proc = subprocess.run(  # noqa: S603 - fixed interpreter, generated script
        ["powershell", "-NoProfile", "-ExecutionPolicy", "Bypass", "-Command", script],
        capture_output=True,
        text=True,
        timeout=90,
        check=False,
    )
    return proc.returncode, (proc.stdout + proc.stderr).strip()


def _shortcut_targets() -> list[Path]:
    home = Path.home()
    targets = [home / "Desktop" / "Thomas.lnk"]
    start_menu = home / "AppData" / "Roaming" / "Microsoft" / "Windows" / "Start Menu" / "Programs"
    if start_menu.exists():
        targets.append(start_menu / "Thomas.lnk")
    return targets


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--port", type=int, default=DEFAULT_PORT)
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    if not sys.platform.startswith("win"):
        print("This installer is Windows-only today; use scripts/create_shortcut.py elsewhere.")
        return 2
    if not ELECTRON_EXE.exists():
        # Not fatal: the shortcut offers to install the shell on first click,
        # and falls back to the browser window if that is declined. Say so here
        # too, so an installer run is not silently a half-installed Thomas.
        print(f"NOTE: {ELECTRON_EXE} is missing.")
        print("      The shortcut will offer to install the desktop shell the first time it is opened.")
        print(f"      To install it now: cd {DESKTOP_DIR} && npm install")

    # Always refresh the icon so the shortcut carries the current brand mark.
    icon_script = REPO_ROOT / "scripts" / "make_thomas_icon.py"
    if icon_script.exists() and not args.dry_run:
        subprocess.run(  # noqa: S603 - our own script, fixed args
            [sys.executable, str(icon_script)], cwd=str(REPO_ROOT), capture_output=True, check=False, timeout=120
        )

    launcher = _LAUNCHER.format(
        port=args.port,
        desktop_dir=str(DESKTOP_DIR),
        electron_exe=str(ELECTRON_EXE),
        run_desktop_ps1=str(RUN_DESKTOP_PS1),
    )
    if args.dry_run:
        print(f"would write {APP_VBS}")
        for target in _shortcut_targets():
            print(f"would create {target} -> {APP_VBS} (icon {ICON})")
        return 0

    APP_VBS.write_text(launcher, encoding="utf-8")
    print(f"wrote {APP_VBS}")

    failures = 0
    for target in _shortcut_targets():
        target.parent.mkdir(parents=True, exist_ok=True)
        code, out = _run_powershell(
            _SHORTCUT_PS1.format(
                lnk=str(target), target=str(APP_VBS), workdir=str(REPO_ROOT), icon=str(ICON)
            )
        )
        if code == 0 and target.exists():
            print(f"created {target}")
        else:
            failures += 1
            print(f"FAILED {target}: {out[:200]}")

    if failures:
        return 1
    print("\nThomas is installed as an app. Open it from the Desktop or Start Menu.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
