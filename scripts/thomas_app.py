"""Install Thomas as a real desktop app, not a browser tab.

Thomas should open the way Claude Code and Codex do — from a shortcut wearing
his own face, straight into his own window. No tabs, no address bar, no
search engine, no other site's chrome. The browser is an implementation
detail; you should not have to see it.

What this installs:
  * ``assets/thomas.ico`` — the two-eyes-in-a-block brand mark (regenerated).
  * ``Thomas.vbs`` — a launcher that opens the Thomas desktop shell in
    ``desktop/``: a real browser engine, so web tabs load sites that refuse to
    be framed. The shell attaches to a running engine or starts one itself, so
    the launcher does not need to wait on health.

    Before 2026-09-02 this launcher opened ``msedge --app=http://127.0.0.1:8899``
    instead. That window could only show web tabs in an iframe, and Gmail, Wells
    Fargo and most other sites refuse to be framed - you clicked a bookmark and
    got "This content is blocked". The desktop shell loads them as top-level
    navigations, which those headers do not apply to. The browser path is kept
    only as a fallback for when ``desktop/node_modules`` has not been installed,
    or when Windows refuses to start the unsigned ``electron.exe``.

    The launcher names no folder: it works out its paths to Thomas's own files from
    where it sits, so the copy tracked in git is the same file whatever machine
    wrote it. When the
    browser path runs on the default port and nothing accepts a connection on
    Thomas's port, it starts the server first instead of opening a window onto a
    dead port, and says so. A machine that is not set up is asked first, because
    the start then runs setup, and the question lists what setup can do; a click
    within half an hour of a start under way asks before starting another.
  * A ``Thomas`` shortcut on the Desktop and in the Start Menu, pointing at
    that launcher with the icon attached.

Usage:
    python scripts/thomas_app.py                 # install (Desktop + Start Menu)
    python scripts/thomas_app.py --port 8899
    python scripts/thomas_app.py --caged         # open the caged Thomas (8898); plain install is the rollback
    python scripts/thomas_app.py --dry-run
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
ICON = REPO_ROOT / "assets" / "thomas.ico"
APP_VBS = REPO_ROOT / "Thomas.vbs"
DESKTOP_DIR = REPO_ROOT / "desktop"
ELECTRON_EXE = DESKTOP_DIR / "node_modules" / "electron" / "dist" / "electron.exe"
DEFAULT_PORT = 8899

_LAUNCHER = """Option Explicit
' Thomas - desktop app launcher (generated by scripts/thomas_app.py).
' Opens the Thomas desktop shell: a real browser engine around the Thomas
' chrome, so a web tab can load a site that refuses to be framed.
' The paths to Thomas's own files are worked out from where this file sits, so
' the same file can sit in any checkout or install. It names no folder, person
' or machine.
Dim shell, fso, appDir, desktopDir, electronExe, runDesktopPs1, launchVbs, runUiPs1
Dim appUrl, profileDir, args, answer, shellFailed, shellNote, startNote, setupAsk

Set shell = CreateObject("WScript.Shell")
Set fso = CreateObject("Scripting.FileSystemObject")
appDir = fso.GetParentFolderName(WScript.ScriptFullName)
desktopDir = appDir & "\\desktop"
electronExe = desktopDir & "\\node_modules\\electron\\dist\\electron.exe"
runDesktopPs1 = appDir & "\\scripts\\run-desktop.ps1"
appUrl = "http://127.0.0.1:{port}/"
shellFailed = False

If fso.FileExists(electronExe) Then
    ' The shell attaches to a running engine or starts one itself, and only
    ' stops an engine it started. Nothing to wait for here.
    ' electron.exe is unsigned, and Windows can refuse to start it (Smart App
    ' Control does). Run then raises an error instead of opening a window, so
    ' catch that and carry on to the browser window below.
    shell.CurrentDirectory = desktopDir
    On Error Resume Next
    shell.Run Chr(34) & electronExe & Chr(34) & " " & Chr(34) & desktopDir & Chr(34) & "{shell_args}", 1, False
    If Err.Number = 0 Then WScript.Quit 0
    Err.Clear
    On Error GoTo 0
    shellFailed = True
    shellNote = "The desktop shell could not be started, so Thomas opens in a browser window."
End If
{start_caged}

' The shell is not built yet - a fresh checkout, or setup was never run.
' run-desktop.ps1 installs the dependencies on first run and then launches, so
' offer that rather than dead-ending in a dialog. Visible window on purpose:
' the install takes a minute and silence reads as nothing happening. Not offered
' when the shell is installed but Windows would not start it: installing again
' cannot help.
If (Not shellFailed) And fso.FileExists(runDesktopPs1) Then
    answer = MsgBox("Thomas needs to finish installing its desktop shell before websites will load in web tabs." & vbCrLf & vbCrLf & _
        "This downloads the browser engine and takes about a minute. It only happens once." & vbCrLf & vbCrLf & _
        "Install it now?", 292, "Thomas")
    If answer = 6 Then
        shell.Run "powershell -NoProfile -ExecutionPolicy Bypass -File " & Chr(34) & runDesktopPs1 & Chr(34), 1, False
        WScript.Quit 0
    End If
End If

' Declined, the installer script is missing, or Windows blocked the shell.
' Thomas still opens, but web tabs fall back to iframes and sites that refuse
' framing will show blank.
{start_plain}
profileDir = shell.ExpandEnvironmentStrings("%LOCALAPPDATA%") & "\\Thomas\\AppWindow"
If Not fso.FolderExists(shell.ExpandEnvironmentStrings("%LOCALAPPDATA%") & "\\Thomas") Then
    fso.CreateFolder shell.ExpandEnvironmentStrings("%LOCALAPPDATA%") & "\\Thomas"
End If
args = " --app=" & appUrl & _
       " --user-data-dir=" & Chr(34) & profileDir & Chr(34) & _
       " --window-size=1440,960 --no-first-run --no-default-browser-check"

On Error Resume Next
shell.Run "msedge" & args, 1, False
If Err.Number <> 0 Then
    Err.Clear
    shell.Run "chrome" & args, 1, False
End If
If Err.Number <> 0 Then
    Err.Clear
    shell.Run appUrl, 1, False
End If
' The shell was installed and Windows would not start it: say why this is a browser window.
If shellFailed Then shell.Popup shellNote, 6, "Thomas", 64
{server_probe}"""

# When the ordinary launcher falls back to a browser window it starts a server only when a
# connection to Thomas's port is refused, and does it the way the everyday launcher does:
# run-ui.ps1 on the default port, which opens Thomas in your browser once it is up, so
# nothing more is opened here. It takes no port, so another --port gets no automatic start.
# Before it starts its own server, run-ui.ps1 stops a Thomas server or tray agent on the
# port, which is why a second start is made over one that may be under way only when you
# say so. (The desktop shell, which the launcher tries first, does its own health check and
# starts a server of its own when that check fails.)
#
# run-ui.ps1 also changes the machine. It works from three files: .venv\Scripts\python.exe
# and .venv\pyvenv.cfg (its Test-VenvValid; without both it builds .venv again, deleting
# one that is there) and runtime\setup\last_setup.txt (without it, it runs scripts\setup.ps1). When any of the
# three is missing the start is shown in a window and asked about first, with the question
# below. When all three are there it is started hidden, as launch-thomas.vbs does, and
# run-ui.ps1 can still, without a question, write the thomas:// link for your Windows
# account, install Python with winget if neither python nor py is on PATH, and pip-install
# Thomas's packages if aiohttp or httpx cannot be imported. The launcher cannot see the last
# two without starting Python or reading PATH, so it does not try. On either path, when the
# server comes up degraded or does not come up (or no free port is found), run-ui.ps1 runs
# Boot Doctor, in a hidden window, which can stop a Thomas process on the port, run pip
# install, change startup files in this folder and, when a model is configured, call it.
# The launcher cannot see that coming either; scripts/README.md lists it.

# What the first start can do, worded for the question: the side effects of run-ui.ps1 and of
# the setup.ps1 it runs on a first start that the test below knows about.
# tests/test_the_shortcut_launcher_setup_question.py reads both scripts and fails when one of
# them gains a winget install or npm call, made through the helpers they use now, that no
# line of this list names, or stops making a change it lists. An install made some other way,
# or a side effect of another kind, is not found: add a line here, and a row to that test's
# table. The box holds about 1000 characters.
_SETUP_QUESTION = (
    "Thomas is not fully set up on this computer.",
    "",
    "Setting it up needs internet access, takes several minutes, and can:",
    "- install Python, with winget, if python and py are not found",
    "- create .venv here (replacing an incomplete one) and install Thomas's Python packages",
    "- install Node.js and Ollama with winget, and the Codex command-line tool with npm, if missing",
    "- run npm install in the desktop folder, which downloads the Electron desktop shell",
    "- change default_model in thomas.toml, and write runtime\\setup\\last_setup.txt",
    "- create or replace the Thomas shortcuts on your Desktop and Start Menu,"
    " and rewrite assets\\thomas.ico and Thomas.vbs",
    "- register the thomas:// link for your Windows account",
    "- start Ollama, if the default model is the local one",
    "",
    "Then it starts Thomas and opens your browser. If Thomas does not start, it runs Boot Doctor,"
    " which can stop a Thomas process, run pip install, change startup files here and, with a model"
    " configured, call it.",
    "",
    "Set Thomas up now?",
)

_START_PLAIN = """
' A connection to Thomas's port was refused: start Thomas the way the everyday
' launcher does, rather than open a window onto a port nothing is listening on.
launchVbs = appDir & "\\launch-thomas.vbs"
runUiPs1 = appDir & "\\scripts\\run-ui.ps1"
If (Not ServerIsUp(appUrl)) And fso.FileExists(launchVbs) And fso.FileExists(runUiPs1) Then
    ' A start that began in the last half hour may still be under way. The connection
    ' was refused, so no Thomas is listening for Yes to stop; any other answer starts nothing.
    If StartIsRunning(runUiPs1, 30 * 60) Then
        answer = MsgBox("Thomas may already be starting: one began in the last half hour and nothing is answering yet." & vbCrLf & vbCrLf & _
            "A first start can install software and take several minutes. If a PowerShell window is open for it, that is where to watch." & vbCrLf & vbCrLf & _
            "Start Thomas again anyway?", 292, "Thomas")
        If answer <> 6 Then WScript.Quit 0
    End If
    ' The three files run-ui.ps1 works from (its Test-VenvValid, and its setup record).
    If fso.FileExists(appDir & "\\.venv\\Scripts\\python.exe") And fso.FileExists(appDir & "\\.venv\\pyvenv.cfg") And fso.FileExists(appDir & "\\runtime\\setup\\last_setup.txt") Then
        startNote = "Starting Thomas. Your browser opens when it is ready."
        If shellFailed Then startNote = startNote & vbCrLf & vbCrLf & shellNote
        shell.Run "wscript.exe //nologo " & Chr(34) & launchVbs & Chr(34), 0, False
        shell.Popup startNote, 5, "Thomas", 64
    Else
        @SETUP_QUESTION@
        answer = MsgBox(setupAsk, 292, "Thomas")
        If answer = 6 Then
            ' -NoExit, as run-ui.cmd has it: if the install fails, its message stays on screen.
            shell.Run "powershell -NoProfile -ExecutionPolicy Bypass -NoExit -File " & Chr(34) & runUiPs1 & Chr(34), 1, False
        Else
            shell.Popup "Nothing was installed and Thomas was not started. Open it again when you want to set it up.", 6, "Thomas", 64
        End If
    End If
    WScript.Quit 0
End If
"""

# Down means one thing only: nothing accepted the connection (&H80072EFD). A timeout
# (&H80072EE2) means something did and is too busy to answer, which happens to a
# Thomas that is running agents or builds, and an odd reply or a failure to ask at
# all is not proof of absence either. Calling any of those down starts a second
# server, which stops the first. The proxy is bypassed so a machine-wide proxy cannot
# make a running server look absent.
_SERVER_PROBE = """
Function ServerIsUp(url)
    Dim http
    ServerIsUp = True
    On Error Resume Next
    Set http = CreateObject("MSXML2.ServerXMLHTTP.6.0")
    http.setProxy 1
    http.setTimeouts 2000, 2000, 3000, 3000
    http.Open "GET", url & "api/health", False
    http.Send
    If Err.Number = &H80072EFD Then ServerIsUp = False
End Function
"""

# Did a run-ui.ps1 of this checkout begin less than maxSeconds ago, and is it still there?
# By default run-ui.ps1 starts a detached server, opens your browser and exits, so one
# is alive only while a start is under way. What can outlive a start is a PowerShell
# window left open around it (run-ui.cmd keeps one, with -NoExit), and that says nothing
# about Thomas, so only a young one counts. The command line must be an invocation
# (-File, then this path), not any shell that mentions the path. A process list or a
# start time that cannot be read counts as "no": the start the launcher would have
# made before it checked.
_START_GUARD = """
Function StartIsRunning(scriptPath, maxSeconds)
    Dim wmi, procs, proc, cmd, age
    StartIsRunning = False
    On Error Resume Next
    Set wmi = GetObject("winmgmts:root\\cimv2")
    If Err.Number <> 0 Then Exit Function
    Set procs = wmi.ExecQuery("SELECT CommandLine, CreationDate FROM Win32_Process WHERE Name = 'powershell.exe' OR Name = 'pwsh.exe'")
    If Err.Number <> 0 Then Exit Function
    For Each proc In procs
        cmd = proc.CommandLine
        If Not IsNull(cmd) Then
            If InStr(1, cmd, "-File " & Chr(34) & scriptPath & Chr(34), vbTextCompare) > 0 Or InStr(1, cmd, "-File " & scriptPath, vbTextCompare) > 0 Then
                age = SecondsSince(proc.CreationDate)
                If Not IsNull(age) Then
                    If age < maxSeconds Then StartIsRunning = True
                End If
            End If
        End If
    Next
End Function

' A WMI start time (yyyymmddHHMMSS.ffffff+UUU, local time) as seconds ago; Null if unreadable.
Function SecondsSince(cim)
    Dim began
    SecondsSince = Null
    On Error Resume Next
    began = DateSerial(CInt(Mid(cim, 1, 4)), CInt(Mid(cim, 5, 2)), CInt(Mid(cim, 7, 2))) + _
        TimeSerial(CInt(Mid(cim, 9, 2)), CInt(Mid(cim, 11, 2)), CInt(Mid(cim, 13, 2)))
    If Err.Number = 0 Then SecondsSince = DateDiff("s", began, Now)
End Function
"""


_SHORTCUT_PS1 = """$ws = New-Object -ComObject WScript.Shell
$sc = $ws.CreateShortcut('{lnk}')
$sc.TargetPath = '{target}'
$sc.WorkingDirectory = '{workdir}'
$sc.IconLocation = '{icon},0'
$sc.Description = 'Thomas'
$sc.WindowStyle = 1
$sc.Save()
"""


CAGED_PORT = 8898
CAGED_TASK = "ThomasCagedServer"


def setup_question_text() -> str:
    """The first-run question as the message box shows it."""
    return "\r\n".join(_SETUP_QUESTION)


def _start_plain() -> str:
    """The automatic-start block, with the first-run question spelled out in VBScript.

    One statement per line: VBScript allows only 24 continuation lines in a statement.
    """
    first, *rest = _SETUP_QUESTION
    statements = [f'setupAsk = "{first}"', *(f'setupAsk = setupAsk & vbCrLf & "{text}"' for text in rest)]
    return _START_PLAIN.replace("@SETUP_QUESTION@", "\n        ".join(statements))


def render_launcher(port: int, *, caged: bool = False) -> str:
    """The launcher text. Caged: open the caged Thomas and start it only by its task.

    The caged server runs as the cage account from a scheduled task you may start
    and stop (scripts/cage/enable_caged_server.ps1). Anything this launcher or the
    desktop shell started itself would run as you, with your rights, which is
    exactly what the cage exists to prevent -- so in caged mode they never do.

    The ordinary launcher on the default port instead starts a server when its
    browser fallback finds nothing accepting connections (see _START_PLAIN).
    """
    shell_args = f" --server-port {port}" + (" --caged" if caged else "")
    start_caged = (
        "\n' Caged: the server runs as the cage account from its own task, never as you.\n"
        f'shell.Run "schtasks /Run /TN {CAGED_TASK}", 0, True\n'
        if caged
        else ""
    )
    starts_plain = not caged and port == DEFAULT_PORT
    return _LAUNCHER.format(
        port=port,
        shell_args=shell_args,
        start_caged=start_caged,
        start_plain=_start_plain() if starts_plain else "",
        server_probe=(_SERVER_PROBE + _START_GUARD) if starts_plain else "",
    )


def _run_powershell(script: str) -> tuple[int, str]:
    proc = subprocess.run(  # noqa: S603 - fixed interpreter, generated script
        ["powershell", "-NoProfile", "-ExecutionPolicy", "Bypass", "-Command", script],
        capture_output=True,
        text=True,
        timeout=90,
        check=False,
    )
    return proc.returncode, (proc.stdout + proc.stderr).strip()


def _shortcut_targets() -> list[Path]:
    home = Path.home()
    targets = [home / "Desktop" / "Thomas.lnk"]
    start_menu = home / "AppData" / "Roaming" / "Microsoft" / "Windows" / "Start Menu" / "Programs"
    if start_menu.exists():
        targets.append(start_menu / "Thomas.lnk")
    return targets


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--port", type=int, default=None)
    parser.add_argument(
        "--caged", action="store_true", help="open the caged Thomas (the cage account's server, port 8898)"
    )
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    port = args.port or (CAGED_PORT if args.caged else DEFAULT_PORT)

    if not sys.platform.startswith("win"):
        print("This installer is Windows-only today; use scripts/create_shortcut.py elsewhere.")
        return 2
    if not ELECTRON_EXE.exists():
        # Not fatal: the shortcut offers to install the shell on first click,
        # and falls back to the browser window if that is declined. Say so here
        # too, so an installer run is not silently a half-installed Thomas.
        print(f"NOTE: {ELECTRON_EXE} is missing.")
        print("      The shortcut will offer to install the desktop shell the first time it is opened.")
        print(f"      To install it now: cd {DESKTOP_DIR} && npm install")

    # Always refresh the icon so the shortcut carries the current brand mark.
    icon_script = REPO_ROOT / "scripts" / "make_thomas_icon.py"
    if icon_script.exists() and not args.dry_run:
        subprocess.run(  # noqa: S603 - our own script, fixed args
            [sys.executable, str(icon_script)], cwd=str(REPO_ROOT), capture_output=True, check=False, timeout=120
        )

    launcher = render_launcher(port, caged=args.caged)
    if args.dry_run:
        print(f"would write {APP_VBS}")
        for target in _shortcut_targets():
            print(f"would create {target} -> {APP_VBS} (icon {ICON})")
        return 0

    APP_VBS.write_text(launcher, encoding="utf-8")
    print(f"wrote {APP_VBS}")

    failures = 0
    for target in _shortcut_targets():
        target.parent.mkdir(parents=True, exist_ok=True)
        code, out = _run_powershell(
            _SHORTCUT_PS1.format(lnk=str(target), target=str(APP_VBS), workdir=str(REPO_ROOT), icon=str(ICON))
        )
        if code == 0 and target.exists():
            print(f"created {target}")
        else:
            failures += 1
            print(f"FAILED {target}: {out[:200]}")

    if failures:
        return 1
    print("\nThomas is installed as an app. Open it from the Desktop or Start Menu.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
