#!/usr/bin/env python3
"""Initialize Agent Safety in a repository.

This is the entry point for making any repo "agent-safe." It:
1. Creates agent_safety.toml with project-specific defaults
2. Copies the enforcement hook scripts
3. Generates a GUARDRAILS.md template
4. Sets up .pre-commit-config.yaml entries
5. Installs the post-commit audit hook

Usage:
    # In any repo root:
    python agent_safety_init.py

    # Or if installed as a package:
    python -m agent_safety init

    # With options:
    python agent_safety_init.py --name "MyProject" --source-dir "src/" --language python
"""

from __future__ import annotations

import argparse
import shutil
import stat
from pathlib import Path
from textwrap import dedent

SCRIPT_DIR = Path(__file__).resolve().parent

# Hook scripts that get copied to the target repo
HOOK_SCRIPTS = [
    "agent_safety_config.py",
    "forge/gates/protected_files_gate.py",
    "forge/gates/exception_handler_gate.py",
    "forge/gates/duplicate_filename_gate.py",
    "forge/gates/circular_imports_gate.py",
    "forge/gates/changelog_gate.py",
    "forge/gates/boot_smoke_gate.py",
    "forge/gates/type_safety_gate.py",
    "post_commit_audit.py",
    "install_post_commit_hook.py",
    "validate_agent_changes.py",
]


def _generate_config(*, name: str, source_dir: str, language: str) -> str:
    """Generate an agent_safety.toml for a new project."""
    source_prefix = source_dir.rstrip("/") + "/"
    module_prefix = source_dir.rstrip("/").replace("/", ".")

    return dedent(f"""\
    # ============================================================================
    # Agent Safety Configuration — {name}
    # ============================================================================
    #
    # This file defines how AI agents must behave in this repository.
    # Every pre-commit hook reads from this file to enforce the rules.
    #
    # Generated by: python agent_safety_init.py
    # Docs: GUARDRAILS.md
    # ============================================================================

    [project]
    name = "{name}"
    language = "{language}"
    source_dirs = ["{source_prefix}", "scripts/"]
    test_dirs = ["tests/"]

    [limits]
    python_soft = 800
    python_hard = 1200
    js_soft = 800
    js_hard = 2000
    css_soft = 600
    css_hard = 1200

    [protected]
    policy_files = ["GUARDRAILS.md", "AGENTS.md"]
    guardrails_files = []
    enforcement_files = ["tests/test_architecture.py"]
    enforcement_scripts = [
        "scripts/validate_agent_changes.py",
        "scripts/forge/gates/protected_files_gate.py",
    ]

    [stubs]
    placeholder_files = []
    build_output_files = []

    [exceptions]
    require_specific = true
    broad_catch_requires = ["logging", "reraise"]
    ratchet = true

    [duplicates]
    forbidden_suffixes = [
        "_v2", "_v3", "_new", "_updated", "_fixed", "_copy",
        "_backup", "_old", "_revised", "_alt", "_temp", "_tmp", "_wip",
        "-v2", "-v3", "-new", "-fixed", "-copy", "-backup", "-old",
    ]
    forbidden_prefixes = ["new_", "new-", "copy_of_", "copy-of-", "backup_", "old_"]

    [changelog]
    required = true
    file = "CHANGELOG.md"
    threshold = 3

    [circular_imports]
    module_prefix = "{module_prefix}"
    forbidden_pairs = []

    [boot_smoke]
    trigger_on_dirs = ["{source_prefix}"]
    imports = ["{module_prefix}"]

    [type_safety]
    enabled = false
    tool = "mypy"
    args = ["--ignore-missing-imports"]
    enabled_files = []

    [skip_policy]
    max_skip_hooks = 4
    max_staged_files_with_skip = 200
    max_staged_files_with_breakglass = 60
    breakglass_max_per_agent_24h = 3
    breakglass_cooldown_minutes = 15
    protected_hooks = []

    [dead_code]
    directories = []
    redirect_to = ""
    """)


def _generate_guardrails(name: str) -> str:
    """Generate a GUARDRAILS.md template."""
    return dedent(f"""\
    # {name} Guardrails — Rules for All AI Agents

    > **THIS FILE IS READ-ONLY POLICY. NO AGENT MAY MODIFY THIS FILE.**
    > If you believe a rule needs changing, STOP and ask the user.

    ## What This File Is

    This file contains rules that ALL AI agents must follow when working on {name}.
    These rules are enforced by pre-commit hooks that automatically reject violations.

    ## Rule 1: File Size Limits

    - No Python file may exceed 800 lines (soft limit).
    - No file may exceed 1200 lines under any circumstance (hard limit).
    - If your implementation would exceed limits, split into multiple files FIRST.

    ## Rule 2: No Modifying Guards

    - `tests/test_architecture.py` is protected. Fix your code, not the test.
    - `GUARDRAILS.md` is protected. Ask the human if a rule needs changing.
    - Enforcement scripts in `scripts/` are protected.

    ## Rule 3: Exception Handling — Be Specific

    - No bare `except:` or `except Exception:` in new code.
    - Every handler must catch a specific type (e.g., `except ValueError:`).
    - If you need a broad catch, you MUST include BOTH logging AND re-raise.

    ## Rule 4: No Duplicate Work

    - Before creating any new file, search for existing implementations.
    - Do not create `_v2.py`, `_new.py`, or `_fixed.py` — fix the original.

    ## Rule 5: Verify Your Work

    After any change:
    1. `python -m py_compile path/to/file.py`
    2. Run the project's test suite
    3. Verify the application still starts

    ## Rule 6: Changelog Is Mandatory

    When you change 3+ code files, update CHANGELOG.md immediately.

    ## Enforcement

    These rules are enforced by pre-commit hooks configured in `.pre-commit-config.yaml`.
    Modifying enforcement mechanisms to bypass rules is itself a rule violation.
    """)


def _generate_precommit_entries() -> str:
    """Generate .pre-commit-config.yaml entries for agent safety hooks."""
    return dedent("""\

      # ── Agent Safety Hooks ────────────────────────────────────────────
      - id: agent-safety-protected-files
        name: Agent Safety - Protected Files
        entry: python scripts/forge/gates/protected_files_gate.py
        language: system
        pass_filenames: false

      - id: agent-safety-exception-handlers
        name: Agent Safety - Exception Handlers
        entry: python scripts/forge/gates/exception_handler_gate.py
        language: system
        pass_filenames: false

      - id: agent-safety-duplicate-filenames
        name: Agent Safety - Duplicate Filenames
        entry: python scripts/forge/gates/duplicate_filename_gate.py
        language: system
        pass_filenames: false

      - id: agent-safety-circular-imports
        name: Agent Safety - Circular Imports
        entry: python scripts/forge/gates/circular_imports_gate.py
        language: system
        pass_filenames: false

      - id: agent-safety-changelog
        name: Agent Safety - Changelog
        entry: python scripts/forge/gates/changelog_gate.py
        language: system
        pass_filenames: false

      - id: agent-safety-boot-smoke
        name: Agent Safety - Boot Smoke
        entry: python scripts/forge/gates/boot_smoke_gate.py
        language: system
        pass_filenames: false
    """)


def run(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Initialize Agent Safety in a repository.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--name", default="", help="Project name (default: directory name)")
    parser.add_argument("--source-dir", default="src", help="Main source directory (default: src)")
    parser.add_argument(
        "--language",
        default="python",
        choices=["python", "javascript", "typescript"],
        help="Primary language (default: python)",
    )
    parser.add_argument("--target", default=".", help="Target repo directory (default: current dir)")
    args = parser.parse_args(argv)

    target = Path(args.target).resolve()
    name = args.name or target.name
    source_dir = args.source_dir

    print(f"Initializing Agent Safety for '{name}' in {target}")
    print()

    # 1. Create agent_safety.toml
    config_path = target / "agent_safety.toml"
    if config_path.exists():
        print("  [skip] agent_safety.toml already exists")
    else:
        config_path.write_text(
            _generate_config(name=name, source_dir=source_dir, language=args.language),
            encoding="utf-8",
        )
        print("  [created] agent_safety.toml")

    # 2. Create GUARDRAILS.md
    guardrails_path = target / "GUARDRAILS.md"
    if guardrails_path.exists():
        print("  [skip] GUARDRAILS.md already exists")
    else:
        guardrails_path.write_text(_generate_guardrails(name), encoding="utf-8")
        print("  [created] GUARDRAILS.md")

    # 3. Copy hook scripts
    scripts_dir = target / "scripts"
    scripts_dir.mkdir(exist_ok=True)
    copied = 0
    for script_name in HOOK_SCRIPTS:
        src = SCRIPT_DIR / script_name
        dst = scripts_dir / script_name
        if not src.exists():
            print(f"  [warn] Source script not found: {src}")
            continue
        if dst.exists():
            print(f"  [skip] scripts/{script_name} already exists")
            continue
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)
        copied += 1
    print(f"  [copied] {copied} hook scripts to scripts/")

    # 4. Show pre-commit config entries
    precommit_path = target / ".pre-commit-config.yaml"
    entries = _generate_precommit_entries()
    if precommit_path.exists():
        content = precommit_path.read_text(encoding="utf-8")
        if "agent-safety" in content:
            print("  [skip] .pre-commit-config.yaml already has agent-safety hooks")
        else:
            print("  [info] Add these entries to your .pre-commit-config.yaml:")
            print(entries)
    else:
        # Create a minimal pre-commit config
        precommit_path.write_text(
            "repos:\n  - repo: local\n    hooks:" + entries,
            encoding="utf-8",
        )
        print("  [created] .pre-commit-config.yaml with agent-safety hooks")

    # 5. Install post-commit audit hook
    git_dir = target / ".git"
    if git_dir.exists():
        hook_path = git_dir / "hooks" / "post-commit"
        marker = "# agent-safety-post-commit-audit"
        hook_content = f"\n{marker}\npython scripts/post_commit_audit.py 2>/dev/null || true\n"

        if hook_path.exists():
            existing = hook_path.read_text(encoding="utf-8")
            if marker in existing:
                print("  [skip] post-commit audit hook already installed")
            else:
                with hook_path.open("a", encoding="utf-8") as f:
                    f.write(hook_content)
                print("  [updated] post-commit audit hook appended")
        else:
            hook_path.parent.mkdir(parents=True, exist_ok=True)
            hook_path.write_text("#!/bin/sh\n" + hook_content, encoding="utf-8")
            hook_path.chmod(hook_path.stat().st_mode | stat.S_IEXEC)
            print("  [created] post-commit audit hook")
    else:
        print("  [skip] No .git directory found (init git first)")

    # 6. Create CHANGELOG.md if missing
    changelog_path = target / "CHANGELOG.md"
    if not changelog_path.exists():
        changelog_path.write_text(
            f"# Changelog\n\nAll notable changes to {name}.\n\n## [Unreleased]\n\n",
            encoding="utf-8",
        )
        print("  [created] CHANGELOG.md")

    print()
    print("Agent Safety initialized!")
    print()
    print("Next steps:")
    print(f"  1. Edit agent_safety.toml to customize rules for {name}")
    print("  2. Run: pip install pre-commit && pre-commit install")
    print("  3. Try a test commit to verify hooks fire")
    print()
    print("When AI agents work on this repo, they'll be governed by")
    print("the rules in agent_safety.toml and GUARDRAILS.md.")

    return 0


if __name__ == "__main__":
    raise SystemExit(run())
