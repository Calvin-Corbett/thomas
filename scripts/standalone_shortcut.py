"""Create a desktop shortcut that opens a Thomas module as its own app.

The standalone principle (docs/EXTENSION_STANDARD.md): any command-center
module can be opened without going through Thomas. This script drops a
launcher on the Desktop that

1. makes sure the local Thomas server is running (starts it hidden via
   launch-thomas.vbs if not),
2. opens ``http://127.0.0.1:<port>/app/<plugin-id>`` in an app-style
   browser window (Edge/Chrome ``--app=`` — no tabs, no address bar),
   falling back to the default browser.

Usage:
    python scripts/standalone_shortcut.py inkwell
    python scripts/standalone_shortcut.py inkwell --name "Inkwell" --port 8899
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent

_LAUNCHER_TEMPLATE = """Option Explicit
' {display_name} — standalone Thomas app launcher (generated by standalone_shortcut.py)
Dim shell, http, appUrl, healthUrl, attempt, started
Set shell = CreateObject("WScript.Shell")
appUrl = "http://127.0.0.1:{port}/app/{plugin_id}"
healthUrl = "http://127.0.0.1:{port}/health/ready"
started = False

Function ServerUp()
    On Error Resume Next
    Dim ping
    Set ping = CreateObject("MSXML2.XMLHTTP")
    ping.Open "GET", healthUrl, False
    ping.Send
    ServerUp = (Err.Number = 0 And ping.Status >= 200 And ping.Status < 500)
    On Error GoTo 0
End Function

If Not ServerUp() Then
    ' Start the Thomas engine hidden, then wait for it to come up.
    shell.Run Chr(34) & "{launch_vbs}" & Chr(34), 0, False
    started = True
    For attempt = 1 To 60
        WScript.Sleep 1000
        If ServerUp() Then Exit For
    Next
End If

If Not ServerUp() Then
    MsgBox "Couldn't start the Thomas engine. Open Thomas once manually, then try again.", _
        48, "{display_name}"
    WScript.Quit 1
End If

' Prefer an app-style window (no tabs/address bar); fall back to default browser.
On Error Resume Next
shell.Run "msedge --app=" & appUrl, 1, False
If Err.Number <> 0 Then
    Err.Clear
    shell.Run "chrome --app=" & appUrl, 1, False
End If
If Err.Number <> 0 Then
    Err.Clear
    shell.Run appUrl, 1, False
End If
"""


def _plugin_display_name(plugin_id: str) -> str:
    manifest_path = REPO_ROOT / "extensions" / plugin_id / "manifest.json"
    if manifest_path.exists():
        try:
            data = json.loads(manifest_path.read_text(encoding="utf-8-sig"))
            name = str(data.get("display_name") or data.get("name") or "").strip()
            if name:
                return name
        except (OSError, UnicodeDecodeError, json.JSONDecodeError):
            pass
    return plugin_id.replace("-", " ").title()


def _desktop_dir() -> Path:
    desktop = Path.home() / "Desktop"
    if not desktop.exists():
        raise SystemExit(f"Desktop folder not found at {desktop}")
    return desktop


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Create a standalone desktop shortcut for a Thomas module")
    parser.add_argument("plugin_id", help="Plugin id, e.g. inkwell")
    parser.add_argument("--name", default="", help="Shortcut display name (default: from manifest)")
    parser.add_argument("--port", type=int, default=8899, help="Thomas server port (default 8899)")
    parser.add_argument("--out-dir", default="", help="Where to write the launcher (default: Desktop)")
    args = parser.parse_args(argv)

    plugin_id = args.plugin_id.strip()
    if not plugin_id or any(ch in plugin_id for ch in '\\/.. "'):
        raise SystemExit("plugin_id must be a simple id like 'inkwell'")

    display_name = args.name.strip() or _plugin_display_name(plugin_id)
    launch_vbs = REPO_ROOT / "launch-thomas.vbs"
    if not launch_vbs.exists():
        raise SystemExit(f"launch-thomas.vbs not found at {launch_vbs}")

    out_dir = Path(args.out_dir) if args.out_dir else _desktop_dir()
    out_path = out_dir / f"{display_name}.vbs"
    script = _LAUNCHER_TEMPLATE.format(
        display_name=display_name.replace('"', ""),
        plugin_id=plugin_id,
        port=args.port,
        launch_vbs=str(launch_vbs),
    )
    out_path.write_text(script, encoding="utf-8")
    print(f"Shortcut created: {out_path}")
    print(f"Double-click it to open {display_name} as its own app (Thomas runs underneath).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
