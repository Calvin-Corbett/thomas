from __future__ import annotations

import base64
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG_PATH = ROOT / "extensions" / "catalog.json"
HOSTED_PLUGINS_ROOT = ROOT / "thomas" / "server" / "plugins_registry" / "plugins"
OUTPUT_TS_PATH = ROOT / "apps" / "site" / "src" / "lib" / "marketplace-snapshot.generated.ts"
OUTPUT_JSON_PATH = ROOT / "apps" / "site" / "src" / "lib" / "marketplace-snapshot.generated.json"


def _read_json(path: Path) -> object:
    return json.loads(path.read_text(encoding="utf-8"))


def build_snapshot() -> dict[str, object]:
    catalog = _read_json(CATALOG_PATH)
    packs = catalog.get("packs") if isinstance(catalog, dict) else []
    hosted_plugins: list[dict[str, object]] = []

    if HOSTED_PLUGINS_ROOT.exists():
        for plugin_dir in sorted(HOSTED_PLUGINS_ROOT.iterdir()):
            if not plugin_dir.is_dir():
                continue
            manifest_path = plugin_dir / "manifest.json"
            bundle_path = plugin_dir / "bundle.zip"
            if not manifest_path.exists() or not bundle_path.exists():
                continue
            bundle_bytes = bundle_path.read_bytes()
            hosted_plugins.append(
                {
                    "id": plugin_dir.name,
                    "bundleBase64": base64.b64encode(bundle_bytes).decode("ascii"),
                    "bundleSizeBytes": len(bundle_bytes),
                    "sha256": hashlib.sha256(bundle_bytes).hexdigest(),
                    "manifest": _read_json(manifest_path),
                }
            )

    return {
        "generatedAt": catalog.get("generated_at", "") if isinstance(catalog, dict) else "",
        "catalogSource": "extensions/catalog.json",
        "packs": packs if isinstance(packs, list) else [],
        "hostedPlugins": hosted_plugins,
    }


def write_snapshot(snapshot: dict[str, object]) -> None:
    payload = json.dumps(snapshot, ensure_ascii=True, separators=(",", ":"), indent=2) + "\n"
    content = (
        "// Generated by scripts/export_site_marketplace_snapshot.py\n"
        'import snapshot from "./marketplace-snapshot.generated.json";\n\n'
        "export const marketplaceSnapshot = snapshot;\n"
    )
    OUTPUT_JSON_PATH.write_text(payload, encoding="utf-8")
    OUTPUT_TS_PATH.write_text(content, encoding="utf-8")


def main() -> None:
    OUTPUT_TS_PATH.parent.mkdir(parents=True, exist_ok=True)
    write_snapshot(build_snapshot())
    print(f"Wrote {OUTPUT_TS_PATH}")
    print(f"Wrote {OUTPUT_JSON_PATH}")


if __name__ == "__main__":
    main()
