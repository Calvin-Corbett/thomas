#!/usr/bin/env python3
"""
scripts/build_module_registry.py
────────────────────────────────
Scans every directory under thomas/ and generates MODULE_REGISTRY.md at the
repo root.  For each module it reports:

  - Whether a STATUS.md exists (and extracts its status + last-assessed date)
  - File count and total lines of Python code
  - Most recently modified .py file and its timestamp

Run:  python scripts/build_module_registry.py

This is safe to re-run at any time.  It overwrites MODULE_REGISTRY.md.
"""

from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
THOMAS_DIR = REPO_ROOT / "thomas"
OUTPUT = REPO_ROOT / "MODULE_REGISTRY.md"

# Directories to skip
SKIP_DIRS = {"__pycache__", ".mypy_cache", ".pytest_cache", "_archived"}


def _parse_status_md(path: Path) -> tuple[str, str]:
    """Extract Status and Last assessed from a STATUS.md table."""
    status = "—"
    assessed = "—"
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
        for line in text.splitlines():
            line_stripped = line.strip().strip("|").strip()
            if line_stripped.lower().startswith("status"):
                parts = [p.strip() for p in line_stripped.split("|")]
                if len(parts) >= 2:
                    status = parts[1]
            elif "last assessed" in line_stripped.lower():
                parts = [p.strip() for p in line_stripped.split("|")]
                if len(parts) >= 2:
                    assessed = parts[1]
    except Exception:
        pass
    return status, assessed


def _scan_module(mod_path: Path) -> dict:
    """Gather stats for one module directory."""
    py_files = list(mod_path.rglob("*.py"))
    py_files = [f for f in py_files if "__pycache__" not in str(f)]

    total_lines = 0
    newest_file = None
    newest_mtime = 0.0
    for f in py_files:
        try:
            total_lines += sum(1 for _ in f.open(encoding="utf-8", errors="replace"))
            mt = f.stat().st_mtime
            if mt > newest_mtime:
                newest_mtime = mt
                newest_file = f
        except Exception:
            pass

    newest_ts = ""
    newest_name = ""
    if newest_file:
        newest_ts = datetime.fromtimestamp(newest_mtime, tz=timezone.utc).strftime("%Y-%m-%d")
        newest_name = newest_file.name

    status_path = mod_path / "STATUS.md"
    has_status = status_path.exists()
    status_val, assessed_val = ("—", "—")
    if has_status:
        status_val, assessed_val = _parse_status_md(status_path)

    return {
        "name": mod_path.name,
        "py_count": len(py_files),
        "total_lines": total_lines,
        "has_status": has_status,
        "status": status_val,
        "assessed": assessed_val,
        "newest_file": newest_name,
        "newest_date": newest_ts,
    }


def main() -> None:
    modules = []
    for entry in sorted(THOMAS_DIR.iterdir()):
        if not entry.is_dir():
            continue
        if entry.name in SKIP_DIRS:
            continue
        if entry.name.startswith("."):
            continue
        modules.append(_scan_module(entry))

    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    has_status_count = sum(1 for m in modules if m["has_status"])
    total_count = len(modules)

    lines = [
        "# Module Registry",
        "",
        f"Auto-generated by `scripts/build_module_registry.py` on {now}.",
        "Re-run anytime: `python scripts/build_module_registry.py`",
        "",
        f"**{has_status_count}/{total_count} modules have a STATUS.md.**",
        "Convention: [docs/STATUS_CONVENTION.md](docs/STATUS_CONVENTION.md)",
        "",
        "| Module | STATUS.md | Status | Assessed | .py files | Lines | Last edit | Newest file |",
        "|--------|-----------|--------|----------|-----------|-------|-----------|-------------|",
    ]

    for m in modules:
        status_icon = "yes" if m["has_status"] else "**NO**"
        lines.append(
            f"| {m['name']} "
            f"| {status_icon} "
            f"| {m['status']} "
            f"| {m['assessed']} "
            f"| {m['py_count']} "
            f"| {m['total_lines']:,} "
            f"| {m['newest_date']} "
            f"| {m['newest_file']} |"
        )

    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("## What To Do With This")
    lines.append("")
    lines.append("1. **If STATUS.md says NO**: that module has not been assessed yet.")
    lines.append("   Before modifying it, create a STATUS.md following the convention.")
    lines.append("2. **If Status is 'scaffold'**: most logic is placeholder. Don't trust")
    lines.append("   its outputs or scores without verifying the code.")
    lines.append("3. **If Assessed date is old**: the assessment may be stale. Re-read")
    lines.append("   the code and update the STATUS.md before relying on it.")
    lines.append("4. **Re-run this script** after adding or updating STATUS.md files")
    lines.append("   to keep the registry current.")
    lines.append("")

    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUTPUT} ({total_count} modules, {has_status_count} with STATUS.md)")


if __name__ == "__main__":
    main()
