"""Carve the repo into plugins: one ordered map, and a manifest generated for each plugin in it.

    python -m scripts.plugins.carve           write plugins/<name>.toml
    python -m scripts.plugins.carve --check   say what would change, and exit 1 if anything would

Spec: docs/superpowers/specs/2026-10-29-kernel-plugins-fast-checks-design.md. A plugin is a manifest over paths: code does
not move to be carved. :data:`MAP` says who owns what, first match wins, and everything else is read from the code:

* ``needs``: what the plugin's code imports from outside it. Each entry is a debt, and the list only shrinks.
* ``door``: what code outside the plugin imports from it. It only shrinks too.
* ``tests``: the tests that touch this plugin and nothing beyond its needs. Others are integration tests, which the full
  check runs.
* ``provides`` and ``uses``: the named calls (``thomas.core.kernel.late``) its code offers and asks for.

plugins/checks.toml is kept by hand: it is the carved example, and its door was narrowed by hand.
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from collections import defaultdict
from dataclasses import replace
from pathlib import Path

from scripts.plugins.plugin_map import MAP, RESERVED_NEEDS

from thomas.core import plugin_fence as fence
from thomas.core.kernel import seams
from thomas.core.plugin_manifest import KERNEL, PluginManifest, claims, load
from thomas.core.plugin_proof import ImportGraph

ROOT = Path(__file__).resolve().parents[2]
_NAMED_CALL = re.compile(r"\blate\.(provide|call)\b[(,]\s*(?:\w*seams)\.([A-Z_]+)")
# What "everything" means: the folders that hold what Thomas is and runs. Documents, plans and tests are not plugins.
CODE_ROOTS = ("thomas/", "scripts/", "evolve_supervisor/", "extensions/", "benchmarks/", "tools/", "desktop/", "web/")
HAND_KEPT = ("checks",)
HEADER = (
    "# Generated by scripts/plugins/carve.py. Spec: docs/superpowers/specs/2026-10-29-kernel-plugins-fast-checks-design.md\n"
    "# needs = what this code imports from outside it; door = what outside code imports from it. Each entry is a debt\n"
    "# that a carve replaces with a kernel seam, a moved function or a passed-in value, and both lists only shrink.\n"
)


def _tracked() -> set[str]:
    out = subprocess.run(["git", "ls-files", "-z"], cwd=ROOT, capture_output=True, check=True, timeout=120).stdout
    return {p.decode("utf-8") for p in out.split(b"\0") if p}


def integration_tests() -> set[str]:
    """Tests measured to need more than their plugin's proof copy. No plugin claims them; the full check runs them."""
    lines = (ROOT / "scripts" / "plugins" / "integration_tests.txt").read_text(encoding="utf-8").splitlines()
    return {line.strip() for line in lines if line.strip() and not line.startswith("#")}


def assign(tracked: set[str]) -> dict[str, set[str]]:
    """Each plugin's files: first match in :data:`MAP` wins. Nothing in the kernel is a plugin's."""
    rules = [(plugin.name, claims(plugin.paths)) for plugin in MAP]
    in_kernel = claims(KERNEL)
    owned: dict[str, set[str]] = defaultdict(set)
    for path in tracked:
        if path.startswith(CODE_ROOTS) and not in_kernel(path):
            owned[next(name for name, claimed in rules if claimed(path))].add(path)
    return owned


def _globs(owned: set[str], tracked: set[str]) -> list[str]:
    """``folder/**`` wherever a whole folder is this plugin's, so a new file there joins it; the files for the rest."""
    under: dict[str, set[str]] = defaultdict(set)
    for path in tracked:
        parts = path.split("/")
        for depth in range(1, len(parts)):
            under["/".join(parts[:depth])].add(path)
    covered: set[str] = set()
    globs = []
    for folder in sorted(under, key=lambda name: (name.count("/"), name)):
        if under[folder] <= owned and not under[folder] <= covered:
            globs.append(f"{folder}/**")
            covered |= under[folder]
    return sorted(globs) + sorted(owned - covered)


def _reach(path: str, graph: ImportGraph) -> set[str]:
    """What a test touches outside ``tests/``, following the helpers it imports, as the proof set reads it."""
    seen, queue, found = {path}, [path], set()
    while queue:
        for target in graph.targets(queue.pop()):
            if not target.startswith("tests/"):
                found.add(target)
            elif target not in seen:
                seen.add(target)
                queue.append(target)
    return found


def _tests_of(
    manifests: dict[str, PluginManifest], sources: dict[str, str], tracked: set[str], taken: set[str]
) -> dict[str, list[str]]:
    """Each test goes to the plugin holding most of what it touches, if everything it touches is that plugin's to use."""
    graph = ImportGraph(tracked, lambda rel: sources.get(rel, ""))
    tests: dict[str, list[str]] = defaultdict(list)
    for path in sorted(tracked):
        if not path.startswith("tests/test_") or not path.endswith(".py") or path in taken:
            continue
        touched = _reach(path, graph)
        fits = [
            (sum(map(manifest.in_code, touched)), name)
            for name, manifest in manifests.items()
            if touched and all(fence._inside(manifest, target) for target in touched)
        ]
        best = max(fits, key=lambda fit: (fit[0], fit[1]), default=(0, ""))
        if best[0]:
            tests[best[1]].append(path)
    return tests


def _needs(manifest: PluginManifest, sources: dict[str, str], tracked: set[str]) -> list[str]:
    roots = fence.repo_roots(tracked)
    needs = set()
    for path, source in sources.items():
        if manifest.in_code(path):
            try:
                found = fence.imports(path, source, roots)
            except SyntaxError:
                continue
            targets = (fence.module_path(module, tracked) for _, module in found)
            needs |= {t for t in targets if t is not None and not fence._inside(manifest, t)}
    return sorted(needs)


def named_calls(manifest: PluginManifest, sources: dict[str, str]) -> tuple[tuple[str, ...], tuple[str, ...]]:
    """What the plugin's code provides and asks for by name: a dependency the import graph cannot show."""
    found: dict[str, set[str]] = {"provide": set(), "call": set()}
    for path, source in sources.items():
        if manifest.in_code(path):
            for verb, name in _NAMED_CALL.findall(source):
                found[verb].add(getattr(seams, name))
    return tuple(sorted(found["provide"])), tuple(sorted(found["call"]))


def carve(tracked: set[str]) -> dict[str, PluginManifest]:
    """Every plugin's manifest, worked out from the map and the code as it stands."""
    owned = assign(tracked)
    sources = {
        p: (ROOT / p).read_text("utf-8", "replace") for p in tracked if p.endswith(".py") and (ROOT / p).is_file()
    }
    hand = {m.name: m for m in load(ROOT) if m.name in HAND_KEPT}
    manifests: dict[str, PluginManifest] = dict(hand)
    for plugin in MAP:
        if plugin.name not in hand and owned.get(plugin.name):
            code = tuple(_globs(owned[plugin.name], tracked))
            manifests[plugin.name] = PluginManifest(
                name=plugin.name, code=code, tests=(), source=f"plugins/{plugin.name}.toml"
            )
    for name, manifest in list(manifests.items()):
        if name not in hand:
            reserved = {path for path, names in RESERVED_NEEDS.items() if name in names and not manifest.in_code(path)}
            needs = tuple(sorted({*_needs(manifest, sources, tracked), *reserved}))
            door = tuple(sorted({target for *_, target in fence.reaches(manifest, sources, tracked)}))
            provides, uses = named_calls(manifest, sources)
            manifests[name] = replace(manifest, needs=needs, door=door, provides=provides, uses=uses)
    taken = {p for m in hand.values() for p in tracked if m.in_tests(p)} | integration_tests()
    assigned = _tests_of(manifests, sources, tracked, taken)
    return {
        name: manifest if name in hand else replace(manifest, tests=tuple(assigned.get(name, ())))
        for name, manifest in manifests.items()
    }


def _block(name: str, values: tuple[str, ...]) -> str:
    if not values:
        return f"{name} = []\n"
    return f"{name} = [\n" + "".join(f"    {json.dumps(value)},\n" for value in values) + "]\n"


def render(manifest: PluginManifest) -> str:
    summary = next(plugin.summary for plugin in MAP if plugin.name == manifest.name)
    body = "".join(
        _block(name, getattr(manifest, name)) for name in ("code", "tests", "needs", "provides", "uses", "door")
    )
    return f"# The {manifest.name} plugin. {summary}\n{HEADER}name = {json.dumps(manifest.name)}\n{body}"


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for name, manifest in sorted(carve(_tracked()).items()):
        if name in HAND_KEPT:
            continue
        path = ROOT / "plugins" / f"{name}.toml"
        text = render(manifest)
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            stale.append(name)
            if not check:
                path.write_bytes(text.encode("utf-8"))
    print(f"{'stale' if check else 'written'}: {', '.join(stale) or 'none'}")
    return 1 if check and stale else 0


__all__ = ["CODE_ROOTS", "MAP", "assign", "carve", "main", "render"]

if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
