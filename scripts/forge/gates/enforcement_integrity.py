#!/usr/bin/env python3
"""Verify that enforcement scripts have not been tampered with.

This script computes SHA-256 hashes of all protected enforcement scripts
and compares them against a known-good manifest. If any script has been
modified (e.g., by a malicious agent rewriting a gate to always pass),
this check fails and blocks the commit.

The integrity manifest (.git/thomas_enforcement_hashes.json) is generated
by running this script with --generate-manifest. The manifest should be
regenerated by the repo owner (human) after any legitimate change to
enforcement scripts.

Defense layer: This closes the "modify the enforcer" attack where an agent
rewrites a hook script to return 0, commits bad code through the weakened
gate, then restores the original script. With integrity checking, the
modified script is detected BEFORE the commit proceeds.

Audit reference: Cowork Adversarial Audit, Layer 1 (2026-03-19)
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
from pathlib import Path

import sys
_REPO_ROOT = Path(__file__).resolve().parents[3]
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

ROOT = Path(__file__).resolve().parents[3]
MANIFEST_PATH = ROOT / ".git" / "thomas_enforcement_hashes.json"

# Self-check: this script's own hash is verified against the manifest too.
# If an attacker modifies this script to skip checks, the post-commit audit
# catches the missing breadcrumb, and the manifest mismatch is visible in
# git diff.
SELF_PATH = "scripts/forge/gates/enforcement_integrity.py"


def _load_protected_scripts() -> list[str]:
    """Load the enforcement script list from agent_safety.toml."""
    try:
        import tomllib

        loader = tomllib
    except ImportError:
        import tomli as loader  # type: ignore[no-redef]

    toml_path = ROOT / "agent_safety.toml"
    if not toml_path.exists():
        return []
    data = loader.loads(toml_path.read_text(encoding="utf-8"))
    scripts = data.get("protected", {}).get("enforcement_scripts", [])
    # Also include this script itself
    if SELF_PATH not in scripts:
        scripts.append(SELF_PATH)
    return [str(s) for s in scripts]


def _hash_file(path: Path) -> str | None:
    """Compute SHA-256 of a file. Returns None if file doesn't exist."""
    if not path.exists():
        return None
    content = path.read_bytes()
    return hashlib.sha256(content).hexdigest()


def _staged_content_hash(rel_path: str) -> str | None:
    """Hash the STAGED version of a file (what will be committed)."""
    proc = subprocess.run(
        ["git", "show", f":{rel_path}"],
        cwd=ROOT,
        capture_output=True,
    )
    if proc.returncode != 0:
        return None
    return hashlib.sha256(proc.stdout).hexdigest()


def generate_manifest(argv: list[str] | None = None) -> int:
    """Generate a fresh integrity manifest from current script contents."""
    scripts = _load_protected_scripts()
    manifest: dict[str, str] = {}

    for rel_path in sorted(scripts):
        full_path = ROOT / rel_path
        file_hash = _hash_file(full_path)
        if file_hash:
            manifest[rel_path] = file_hash

    MANIFEST_PATH.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST_PATH.write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    print(f"Integrity manifest written: {len(manifest)} scripts hashed")
    print(f"  Location: {MANIFEST_PATH}")
    return 0


def verify(argv: list[str] | None = None) -> int:
    """Verify enforcement scripts against the manifest."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json", action="store_true")
    parser.add_argument(
        "--generate-manifest", action="store_true", help="Generate a fresh manifest (human-only operation)"
    )
    parser.add_argument("--check-staged", action="store_true", help="Check staged versions instead of working tree")
    args = parser.parse_args(argv)

    if args.generate_manifest:
        return generate_manifest()

    if not MANIFEST_PATH.exists():
        # No manifest yet — generate one on first run so the system
        # bootstraps itself. After this, any tampering is detected.
        print("No integrity manifest found — generating initial manifest.")
        print("Future runs will detect any tampering.")
        return generate_manifest()

    manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    scripts = _load_protected_scripts()
    tampered: list[dict[str, str]] = []
    missing_from_manifest: list[str] = []

    for rel_path in sorted(scripts):
        expected_hash = manifest.get(rel_path)
        if expected_hash is None:
            # New script added to protected list but not in manifest.
            # Not a tampering signal, but worth noting.
            missing_from_manifest.append(rel_path)
            continue

        if args.check_staged:
            actual_hash = _staged_content_hash(rel_path)
        else:
            actual_hash = _hash_file(ROOT / rel_path)

        if actual_hash is None:
            tampered.append(
                {
                    "path": rel_path,
                    "reason": "file_missing",
                    "expected": expected_hash[:12],
                    "actual": "MISSING",
                }
            )
        elif actual_hash != expected_hash:
            tampered.append(
                {
                    "path": rel_path,
                    "reason": "hash_mismatch",
                    "expected": expected_hash[:12],
                    "actual": actual_hash[:12],
                }
            )

    ok = len(tampered) == 0

    if args.json:
        print(
            json.dumps(
                {
                    "gate": "enforcement_integrity",
                    "ok": ok,
                    "tampered": tampered,
                    "scripts_checked": len(scripts),
                    "missing_from_manifest": missing_from_manifest,
                },
                sort_keys=True,
            )
        )
    else:
        if ok:
            note = ""
            if missing_from_manifest:
                note = f" ({len(missing_from_manifest)} new scripts not yet in manifest)"
            print(f"Enforcement integrity: PASS ({len(scripts)} scripts){note}")
        else:
            print("SAFETY GATE FAILED: Enforcement Scripts Tampered")
            print("=" * 70)
            print()
            print("WHAT HAPPENED:")
            print("  One or more enforcement scripts have been modified since the")
            print("  last known-good state. This could mean:")
            print("    - A malicious agent rewrote a gate to always pass")
            print("    - A legitimate change was made without updating the manifest")
            print()
            print("TAMPERED FILES:")
            for item in tampered:
                print(f"  - {item['path']}")
                print(f"    Expected hash: {item['expected']}...")
                print(f"    Actual:        {item['actual']}...")
            print()
            print("IF THIS IS LEGITIMATE:")
            print("  The repo owner (human) should regenerate the manifest:")
            print("    python scripts/forge/gates/enforcement_integrity.py --generate-manifest")
            print()
            print("IF THIS IS SUSPICIOUS:")
            print("  Restore the scripts from git:")
            for item in tampered:
                print(f"    git checkout HEAD -- {item['path']}")
            print("=" * 70)

    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(verify())
