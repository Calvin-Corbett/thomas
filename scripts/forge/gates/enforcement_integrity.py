#!/usr/bin/env python3
"""Verify that enforcement scripts have not been tampered with.

This script computes SHA-256 hashes of all protected enforcement scripts
and compares them against a known-good manifest. If any script has been
modified (e.g., by a malicious agent rewriting a gate to always pass),
this check fails and blocks the commit.

The integrity manifest (.git/thomas_enforcement_hashes.json) is generated
by running this script with --generate-manifest. The manifest should be
regenerated by the repo owner (human) after any legitimate change to
enforcement scripts.

Defense layer: This closes the "modify the enforcer" attack where an agent
rewrites a hook script to return 0, commits bad code through the weakened
gate, then restores the original script. With integrity checking, the
modified script is detected BEFORE the commit proceeds.

Audit reference: Cowork Adversarial Audit, Layer 1 (2026-03-19)
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parents[3]
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

ROOT = Path(__file__).resolve().parents[3]
# The manifest is a TRACKED file (not in .git/) so that:
#   - tampering with a gate script forces a manifest change that is visible in
#     the PR diff and (with branch protection) needs CODEOWNERS review;
#   - the server-side gates.yml job can verify scripts against it;
#   - it cannot be silently deleted + regenerated locally to re-bless tampered
#     scripts (the old .git/ trust-on-first-use bypass, B7).
# It lives under scripts/ which is a filesystem-protected dir, so the agent's
# sanctioned fs tools refuse to write it.
MANIFEST_PATH = ROOT / "scripts" / "forge" / "gates" / "enforcement_manifest.json"

# Self-check: this script's own hash is verified against the manifest too.
# If an attacker modifies this script to skip checks, the post-commit audit
# catches the missing breadcrumb, and the manifest mismatch is visible in
# git diff.
SELF_PATH = "scripts/forge/gates/enforcement_integrity.py"


def _load_protected_scripts() -> list[str]:
    """Load the enforcement script list from agent_safety.toml."""
    try:
        import tomllib

        loader = tomllib
    except ImportError:
        import tomli as loader  # type: ignore[no-redef]

    toml_path = ROOT / "agent_safety.toml"
    if not toml_path.exists():
        # Fail closed: even with no config we must still self-check this script
        # (and verify() additionally re-checks every manifest entry). The old
        # behavior returned [] -- so deleting agent_safety.toml collapsed the
        # protected list to empty and verify() passed while checking nothing.
        return [SELF_PATH]
    data = loader.loads(toml_path.read_text(encoding="utf-8"))
    scripts = data.get("protected", {}).get("enforcement_scripts", [])
    # Also include this script itself
    if SELF_PATH not in scripts:
        scripts.append(SELF_PATH)
    return [str(s) for s in scripts]


def _normalize(content: bytes) -> bytes:
    """Normalize line endings before hashing (B14).

    Without this, the worktree bytes (CRLF on a Windows checkout) hash
    differently from the staged/committed blob bytes (LF after .gitattributes
    normalization), so `--check-staged` and the CI checkout disagree with a
    manifest generated from the worktree. Normalizing CRLF→LF makes all three
    modes — worktree, staged, and CI checkout — produce identical hashes.
    """
    return content.replace(b"\r\n", b"\n")


def _hash_file(path: Path) -> str | None:
    """Compute SHA-256 of a file's line-ending-normalized bytes. None if absent."""
    if not path.exists():
        return None
    return hashlib.sha256(_normalize(path.read_bytes())).hexdigest()


def _staged_content_hash(rel_path: str) -> str | None:
    """Hash the STAGED (index) version of a file (what will be committed)."""
    proc = subprocess.run(
        ["git", "show", f":{rel_path}"],
        cwd=ROOT,
        capture_output=True,
    )
    if proc.returncode != 0:
        return None
    return hashlib.sha256(_normalize(proc.stdout)).hexdigest()


def generate_manifest(argv: list[str] | None = None) -> int:
    """Generate a fresh integrity manifest from current script contents."""
    scripts = _load_protected_scripts()
    manifest: dict[str, str] = {}

    for rel_path in sorted(scripts):
        full_path = ROOT / rel_path
        file_hash = _hash_file(full_path)
        if file_hash:
            manifest[rel_path] = file_hash

    MANIFEST_PATH.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST_PATH.write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    print(f"Integrity manifest written: {len(manifest)} scripts hashed")
    print(f"  Location: {MANIFEST_PATH}")
    return 0


def verify(argv: list[str] | None = None) -> int:
    """Verify enforcement scripts against the manifest."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json", action="store_true")
    parser.add_argument(
        "--generate-manifest", action="store_true", help="Generate a fresh manifest (human-only operation)"
    )
    parser.add_argument("--check-staged", action="store_true", help="Check staged versions instead of working tree")
    args = parser.parse_args(argv)

    if args.generate_manifest:
        return generate_manifest()

    if not MANIFEST_PATH.exists():
        # B7 (praxis-unbypassable-2026-05-29): fail CLOSED on a missing manifest.
        # The old behavior auto-generated a manifest from the CURRENT scripts and
        # returned PASS — so an attacker could delete the manifest, tamper a gate
        # to always pass, and the next run would re-bless the tampered script.
        # The manifest is a committed, reviewed artifact; if it is missing the
        # repo owner must (re)generate it deliberately.
        msg = (
            "SAFETY GATE FAILED: enforcement integrity manifest is missing\n"
            f"  expected: {MANIFEST_PATH.relative_to(ROOT)}\n"
            "  A missing manifest cannot attest that gate scripts are untampered.\n"
            "  The repo owner regenerates it (after reviewing the gate scripts):\n"
            "    python scripts/forge/gates/enforcement_integrity.py --generate-manifest\n"
            "  then commits the manifest."
        )
        if args.json:
            print(
                json.dumps({"gate": "enforcement_integrity", "ok": False, "error": "manifest_missing"}, sort_keys=True)
            )
        else:
            print(msg)
        return 1

    manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    scripts = _load_protected_scripts()
    # Verify the UNION of the live protected list and the manifest keys so that
    # neither side can shrink coverage on its own:
    #   - every manifest entry is checked even if agent_safety.toml was edited
    #     or deleted to drop it from the protected list (defeats the "remove the
    #     gate from the config to un-protect it" bypass);
    #   - a protected-list entry with NO manifest hash now FAILS closed, instead
    #     of passing as merely "missing_from_manifest" advisory -- that gap let
    #     an active hook (e.g. the pre-push secret-scan preflight) sit on the
    #     protected list yet be silently rewritable with zero integrity alarm.
    checklist = sorted(set(scripts) | set(manifest.keys()))
    tampered: list[dict[str, str]] = []
    missing_from_manifest: list[str] = []

    for rel_path in checklist:
        expected_hash = manifest.get(rel_path)
        if expected_hash is None:
            # On the protected list but never hashed -> we cannot attest it is
            # untampered, so a malicious rewrite would go undetected. Fail
            # closed; the repo owner regenerates the manifest after review.
            missing_from_manifest.append(rel_path)
            continue

        if args.check_staged:
            actual_hash = _staged_content_hash(rel_path)
        else:
            actual_hash = _hash_file(ROOT / rel_path)

        if actual_hash is None:
            tampered.append(
                {
                    "path": rel_path,
                    "reason": "file_missing",
                    "expected": expected_hash[:12],
                    "actual": "MISSING",
                }
            )
        elif actual_hash != expected_hash:
            tampered.append(
                {
                    "path": rel_path,
                    "reason": "hash_mismatch",
                    "expected": expected_hash[:12],
                    "actual": actual_hash[:12],
                }
            )

    ok = len(tampered) == 0 and len(missing_from_manifest) == 0

    if args.json:
        print(
            json.dumps(
                {
                    "gate": "enforcement_integrity",
                    "ok": ok,
                    "tampered": tampered,
                    "scripts_checked": len(checklist),
                    "missing_from_manifest": missing_from_manifest,
                },
                sort_keys=True,
            )
        )
    else:
        if ok:
            print(f"Enforcement integrity: PASS ({len(checklist)} scripts)")
        else:
            print("SAFETY GATE FAILED: Enforcement Scripts Tampered Or Uncovered")
            print("=" * 70)
            print()
            print("WHAT HAPPENED:")
            print("  One or more enforcement scripts cannot be attested as the")
            print("  last known-good state. This could mean:")
            print("    - A malicious agent rewrote a gate to always pass")
            print("    - A protected gate has no known-good hash to compare against")
            print("    - A legitimate change was made without updating the manifest")
            if tampered:
                print()
                print("TAMPERED FILES:")
                for item in tampered:
                    print(f"  - {item['path']}")
                    print(f"    Expected hash: {item['expected']}...")
                    print(f"    Actual:        {item['actual']}...")
            if missing_from_manifest:
                print()
                print("PROTECTED SCRIPTS WITH NO MANIFEST HASH (cannot attest untampered):")
                for path in missing_from_manifest:
                    print(f"  - {path}")
                print("  A protected gate with no hash could be silently rewritten;")
                print("  failing closed until the repo owner hashes it (see below).")
            print()
            print("IF THIS IS LEGITIMATE:")
            print("  The repo owner (human) should regenerate the manifest:")
            print("    python scripts/forge/gates/enforcement_integrity.py --generate-manifest")
            if tampered:
                print()
                print("IF THIS IS SUSPICIOUS:")
                print("  Restore the scripts from git:")
                for item in tampered:
                    print(f"    git checkout HEAD -- {item['path']}")
            print("=" * 70)

    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(verify())
