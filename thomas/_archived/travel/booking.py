"""Booking engine with PNR generation and booking lifecycle management."""

import random
import string
from datetime import datetime
from decimal import Decimal

from thomas.travel._exceptions import BookingError, InvalidPassportError, PaymentError
from thomas.travel._types import Booking, BookingStatus, FareClass, Flight, Passenger, Seat


class PNRGenerator:
    """Generate and manage Passenger Name Records (PNRs)."""

    def __init__(self) -> None:
        """Initialize PNR generator."""
        self._generated_pnrs: set[str] = set()

    def generate_pnr(self) -> str:
        """
        Generate unique 6-character PNR.

        Returns:
            PNR code
        """
        while True:
            # Generate 6 random alphanumeric characters
            pnr = "".join(random.choices(string.ascii_uppercase + string.digits, k=6))
            if pnr not in self._generated_pnrs:
                self._generated_pnrs.add(pnr)
                return pnr

    def validate_pnr(self, pnr: str) -> bool:
        """
        Validate PNR format and existence.

        Args:
            pnr: PNR code

        Returns:
            True if valid
        """
        if not pnr or len(pnr) != 6:
            return False
        return all(c in string.ascii_uppercase + string.digits for c in pnr)

    def is_generated(self, pnr: str) -> bool:
        """
        Check if PNR was generated by this system.

        Args:
            pnr: PNR code

        Returns:
            True if PNR was generated
        """
        return pnr in self._generated_pnrs


class PassengerValidator:
    """Validate passenger information for bookings."""

    @staticmethod
    def validate_passenger(passenger: Passenger, travel_date: datetime) -> bool:
        """
        Validate passenger information.

        Args:
            passenger: Passenger object
            travel_date: Travel date

        Returns:
            True if passenger valid

        Raises:
            InvalidPassportError: If passport invalid
        """
        if passenger.passport_number and not passenger.is_passport_valid(travel_date):
            raise InvalidPassportError(f"Passport expired for {passenger.full_name}")

        return True

    @staticmethod
    def validate_passengers(
        passengers: list[Passenger],
        travel_date: datetime,
    ) -> bool:
        """
        Validate all passengers.

        Args:
            passengers: List of passengers
            travel_date: Travel date

        Returns:
            True if all valid

        Raises:
            InvalidPassportError: If any passenger invalid
        """
        for passenger in passengers:
            PassengerValidator.validate_passenger(passenger, travel_date)
        return True


class SeatAssignment:
    """Assign seats to passengers."""

    def __init__(self, flight: Flight) -> None:
        """
        Initialize seat assigner.

        Args:
            flight: Flight object
        """
        self.flight = flight
        self._assignments: dict[str, str] = {}  # passenger_id -> seat_number

    def assign_seats(
        self,
        passengers: list[Passenger],
        fare_class: FareClass,
        preferences: dict[str, str] | None = None,
    ) -> dict[str, str]:
        """
        Assign seats to passengers.

        Args:
            passengers: List of passengers
            fare_class: Fare class
            preferences: Optional seat preferences by passenger name

        Returns:
            Dictionary of passenger_name -> seat_number

        Raises:
            BookingError: If insufficient seats available
        """
        available_seats = self.flight.available_seats_by_class(fare_class)

        if len(available_seats) < len(passengers):
            raise BookingError(f"Not enough {fare_class.value} seats available")

        # Sort seats by preference (window, aisle, etc.)
        sorted_seats = sorted(available_seats, key=lambda s: self._seat_score(s, preferences))

        assignments = {}
        for i, passenger in enumerate(passengers):
            seat = sorted_seats[i]
            seat.is_available = False
            assignments[passenger.full_name] = seat.seat_number
            self._assignments[passenger.full_name] = seat.seat_number

        return assignments

    def _seat_score(
        self,
        seat: Seat,
        preferences: dict[str, str] | None = None,
    ) -> int:
        """
        Calculate score for seat assignment.

        Args:
            seat: Seat object
            preferences: User preferences

        Returns:
            Score (lower is better)
        """
        score = int(seat.row)

        # Prefer extra legroom
        if seat.extra_legroom:
            score -= 10

        # Avoid emergency exits
        if seat.is_emergency_exit:
            score += 100

        return score

    def get_assignment(self, passenger_name: str) -> str | None:
        """
        Get seat assignment for passenger.

        Args:
            passenger_name: Passenger name

        Returns:
            Seat number, or None
        """
        return self._assignments.get(passenger_name)


class BookingWorkflow:
    """Manage booking workflow stages."""

    def __init__(self, pnr_gen: PNRGenerator) -> None:
        """
        Initialize booking workflow.

        Args:
            pnr_gen: PNR generator
        """
        self.pnr_gen = pnr_gen
        self._bookings: dict[str, Booking] = {}
        self._booking_sessions: dict[str, dict] = {}  # session_id -> booking_data

    def create_booking_session(
        self,
        flight: Flight,
        fare_class: FareClass,
    ) -> str:
        """
        Create booking session for search-to-confirmation workflow.

        Args:
            flight: Selected flight
            fare_class: Selected fare class

        Returns:
            Session ID

        Raises:
            BookingError: If flight not available
        """
        session_id = self._generate_session_id()
        self._booking_sessions[session_id] = {
            "flight": flight,
            "fare_class": fare_class,
            "passengers": [],
            "status": BookingStatus.SEARCH,
            "created": datetime.utcnow(),
        }
        return session_id

    def add_passengers(
        self,
        session_id: str,
        passengers: list[Passenger],
    ) -> None:
        """
        Add passengers to booking.

        Args:
            session_id: Booking session ID
            passengers: List of passengers

        Raises:
            BookingError: If session not found
        """
        if session_id not in self._booking_sessions:
            raise BookingError(f"Booking session {session_id} not found")

        session = self._booking_sessions[session_id]
        session["passengers"] = passengers
        session["status"] = BookingStatus.PASSENGER_DETAILS

    def process_payment(
        self,
        session_id: str,
        payment_method: str,
        total_price: Decimal,
    ) -> bool:
        """
        Process payment for booking.

        Args:
            session_id: Booking session ID
            payment_method: Payment method
            total_price: Total price

        Returns:
            True if payment successful

        Raises:
            PaymentError: If payment fails
            BookingError: If session not found
        """
        if session_id not in self._booking_sessions:
            raise BookingError(f"Booking session {session_id} not found")

        session = self._booking_sessions[session_id]

        # Simulate payment processing
        if not self._validate_payment(payment_method, total_price):
            raise PaymentError("Payment declined")

        session["payment_method"] = payment_method
        session["total_price"] = total_price
        session["status"] = BookingStatus.PAYMENT
        return True

    def confirm_booking(self, session_id: str) -> Booking:
        """
        Confirm booking and generate PNR.

        Args:
            session_id: Booking session ID

        Returns:
            Confirmed Booking object

        Raises:
            BookingError: If session not ready for confirmation
        """
        if session_id not in self._booking_sessions:
            raise BookingError(f"Booking session {session_id} not found")

        session = self._booking_sessions[session_id]

        if not session.get("payment_method"):
            raise BookingError("Payment not processed")

        if not session.get("passengers"):
            raise BookingError("No passengers added")

        # Generate PNR
        pnr = self.pnr_gen.generate_pnr()

        # Assign seats
        seat_assigner = SeatAssignment(session["flight"])
        seat_assignments = seat_assigner.assign_seats(
            session["passengers"],
            session["fare_class"],
        )

        # Create seats dict
        seats = {}
        for passenger_name, seat_num in seat_assignments.items():
            seats[passenger_name] = session["flight"].seats.get(seat_num)

        # Create booking
        booking = Booking(
            pnr=pnr,
            flight=session["flight"],
            passengers=session["passengers"],
            fare_class=session["fare_class"],
            seats=seats,
            status=BookingStatus.CONFIRMED,
            booking_date=datetime.utcnow(),
            price=session.get("total_price", Decimal("0")),
            payment_method=session.get("payment_method"),
            confirmation_sent=False,
        )

        self._bookings[pnr] = booking
        session["status"] = BookingStatus.CONFIRMED
        return booking

    def get_booking(self, pnr: str) -> Booking | None:
        """
        Retrieve booking by PNR.

        Args:
            pnr: PNR code

        Returns:
            Booking object, or None
        """
        return self._bookings.get(pnr)

    def _validate_payment(self, payment_method: str, amount: Decimal) -> bool:
        """
        Validate payment (stub for payment processor).

        Args:
            payment_method: Payment method
            amount: Amount to charge

        Returns:
            True if valid
        """
        # Simulate payment validation
        return len(payment_method) > 0 and amount > Decimal("0")

    def _generate_session_id(self) -> str:
        """
        Generate booking session ID.

        Returns:
            Session ID
        """
        return "".join(random.choices(string.ascii_letters + string.digits, k=12))


class BookingModificationEngine:
    """Handle booking modifications: date changes, name corrections, etc."""

    def __init__(self) -> None:
        """Initialize modification engine."""
        self._modification_history: dict[str, list[dict]] = {}

    def change_date(
        self,
        pnr: str,
        booking: Booking,
        new_date: datetime,
        change_fee: Decimal,
    ) -> dict[str, any]:
        """
        Change flight date.

        Args:
            pnr: PNR code
            booking: Current booking
            new_date: New departure date
            change_fee: Fee for change

        Returns:
            Modification details

        Raises:
            BookingError: If date change not allowed
        """
        if pnr not in self._modification_history:
            self._modification_history[pnr] = []

        modification = {
            "type": "date_change",
            "old_date": booking.flight.departure_time,
            "new_date": new_date,
            "change_fee": change_fee,
            "timestamp": datetime.utcnow(),
        }

        self._modification_history[pnr].append(modification)
        return modification

    def correct_passenger_name(
        self,
        pnr: str,
        passenger_index: int,
        corrected_name: str,
    ) -> dict[str, any]:
        """
        Correct passenger name on booking.

        Args:
            pnr: PNR code
            passenger_index: Passenger index
            corrected_name: Corrected name

        Returns:
            Modification details
        """
        if pnr not in self._modification_history:
            self._modification_history[pnr] = []

        modification = {
            "type": "name_correction",
            "passenger_index": passenger_index,
            "corrected_name": corrected_name,
            "timestamp": datetime.utcnow(),
        }

        self._modification_history[pnr].append(modification)
        return modification

    def add_service(
        self,
        pnr: str,
        service_type: str,
        service_fee: Decimal,
    ) -> dict[str, any]:
        """
        Add service to booking (baggage, seat selection, etc.).

        Args:
            pnr: PNR code
            service_type: Service type
            service_fee: Service fee

        Returns:
            Service details
        """
        if pnr not in self._modification_history:
            self._modification_history[pnr] = []

        modification = {
            "type": "add_service",
            "service": service_type,
            "fee": service_fee,
            "timestamp": datetime.utcnow(),
        }

        self._modification_history[pnr].append(modification)
        return modification

    def get_modification_history(self, pnr: str) -> list[dict]:
        """
        Get modification history for booking.

        Args:
            pnr: PNR code

        Returns:
            List of modifications
        """
        return self._modification_history.get(pnr, [])


class CancellationEngine:
    """Handle booking cancellations and refunds."""

    def __init__(self) -> None:
        """Initialize cancellation engine."""
        self._cancellations: dict[str, dict] = {}

    def cancel_booking(
        self,
        pnr: str,
        booking: Booking,
        cancellation_reason: str = "",
    ) -> dict[str, any]:
        """
        Cancel booking and calculate refund.

        Args:
            pnr: PNR code
            booking: Booking to cancel
            cancellation_reason: Reason for cancellation

        Returns:
            Cancellation details with refund amount

        Raises:
            BookingError: If booking already cancelled
        """
        if pnr in self._cancellations:
            raise BookingError(f"Booking {pnr} already cancelled")

        # Calculate refund based on fare rules
        refund = self._calculate_refund(booking)

        cancellation = {
            "pnr": pnr,
            "cancellation_date": datetime.utcnow(),
            "original_price": booking.price,
            "refund_amount": refund,
            "reason": cancellation_reason,
            "status": "cancelled",
        }

        self._cancellations[pnr] = cancellation
        return cancellation

    def _calculate_refund(self, booking: Booking) -> Decimal:
        """
        Calculate refund amount.

        Args:
            booking: Booking to cancel

        Returns:
            Refund amount
        """
        days_until_flight = (booking.flight.departure_time.date() - datetime.utcnow().date()).days

        # Full refund if cancelled > 7 days before
        if days_until_flight > 7:
            return booking.price

        # 50% refund if cancelled 3-7 days before
        if days_until_flight > 3:
            return booking.price * Decimal("0.5")

        # 25% refund if cancelled < 3 days before
        if days_until_flight > 0:
            return booking.price * Decimal("0.25")

        # No refund if already departed
        return Decimal("0")

    def get_cancellation(self, pnr: str) -> dict | None:
        """
        Get cancellation details.

        Args:
            pnr: PNR code

        Returns:
            Cancellation details, or None
        """
        return self._cancellations.get(pnr)


class WaitlistManager:
    """Manage flight waitlist for fully booked flights."""

    def __init__(self) -> None:
        """Initialize waitlist manager."""
        self._waitlists: dict[str, list[dict]] = {}  # flight_id -> waitlist

    def add_to_waitlist(
        self,
        flight_id: str,
        passenger_name: str,
        email: str,
        fare_class: FareClass,
    ) -> dict[str, any]:
        """
        Add passenger to waitlist.

        Args:
            flight_id: Flight identifier
            passenger_name: Passenger name
            email: Passenger email
            fare_class: Desired fare class

        Returns:
            Waitlist entry
        """
        if flight_id not in self._waitlists:
            self._waitlists[flight_id] = []

        position = len(self._waitlists[flight_id]) + 1

        entry = {
            "position": position,
            "passenger_name": passenger_name,
            "email": email,
            "fare_class": fare_class,
            "added_date": datetime.utcnow(),
            "confirmed": False,
        }

        self._waitlists[flight_id].append(entry)
        return entry

    def get_waitlist(self, flight_id: str) -> list[dict]:
        """
        Get waitlist for flight.

        Args:
            flight_id: Flight identifier

        Returns:
            List of waitlist entries
        """
        return self._waitlists.get(flight_id, [])

    def confirm_from_waitlist(
        self,
        flight_id: str,
        position: int,
    ) -> dict | None:
        """
        Confirm passenger from waitlist.

        Args:
            flight_id: Flight identifier
            position: Waitlist position

        Returns:
            Confirmed entry, or None
        """
        if flight_id not in self._waitlists:
            return None

        waitlist = self._waitlists[flight_id]
        for entry in waitlist:
            if entry["position"] == position:
                entry["confirmed"] = True
                return entry

        return None
