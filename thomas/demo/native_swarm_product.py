"""Product-build fixture for Thomas-native swarm benchmarks."""

from __future__ import annotations

import json
import subprocess
from dataclasses import dataclass
from pathlib import Path
from typing import Any

FEATURE_CATEGORIES = ("intake", "planning", "execution", "review", "governance")


@dataclass(frozen=True)
class LaneSpec:
    lane: int
    agent: str
    scope: str
    path: Path


def lane_specs(root: Path, count: int) -> list[LaneSpec]:
    features_dir = root / "product" / "features"
    return [
        LaneSpec(
            lane=lane,
            agent=f"thomas-native-swarm-worker-{lane:02d}",
            scope=str((features_dir / f"feature-{lane:02d}.mjs").relative_to(root.parent.parent)),
            path=features_dir / f"feature-{lane:02d}.mjs",
        )
        for lane in range(1, count + 1)
    ]


def write_scaffold(root: Path, count: int) -> None:
    (root / "product" / "features").mkdir(parents=True, exist_ok=True)
    (root / "product" / "scripts").mkdir(parents=True, exist_ok=True)
    (root / "product" / "src").mkdir(parents=True, exist_ok=True)
    specs = lane_specs(root, count)
    (root / "SPEC.md").write_text(_spec_text(count), encoding="utf-8")
    (root / "scopes.txt").write_text("\n".join(spec.scope for spec in specs) + "\n", encoding="utf-8")
    (root / "product" / "index.html").write_text(_index_html(), encoding="utf-8")
    (root / "product" / "src" / "app.mjs").write_text(_app_js(count), encoding="utf-8")
    (root / "product" / "src" / "styles.css").write_text(_styles_css(), encoding="utf-8")
    (root / "product" / "scripts" / "evaluate.mjs").write_text(_evaluator_js(count), encoding="utf-8")


def mock_payload(lane: int) -> dict[str, Any]:
    category = FEATURE_CATEGORIES[(lane - 1) % len(FEATURE_CATEGORIES)]
    return {
        "title": f"{category.title()} Control {lane:02d}",
        "category": category,
        "metric": f"{80 + lane}% readiness",
        "accent": f"#{(0x335577 + lane * 34567) % 0xFFFFFF:06x}",
        "problem": f"Lane {lane:02d} reduces coordination risk for high-volume agent work.",
        "workflow": [
            f"Capture lane {lane:02d} input",
            "Validate scope and ownership",
            "Publish reviewable output",
        ],
        "acceptanceChecks": [
            "Stable feature id",
            "Correct owner lane",
            "Renderable card content",
        ],
        "implementationNotes": "Generated by the host-scoped Thomas-native benchmark path.",
    }


def normalize_payload(lane: int, payload: dict[str, Any]) -> dict[str, Any]:
    def text(key: str, fallback: str) -> str:
        value = str(payload.get(key) or fallback).strip()
        return value[:240] if value else fallback

    def items(key: str, fallback: list[str]) -> list[str]:
        raw = payload.get(key)
        if not isinstance(raw, list):
            return fallback
        out = [str(item).strip()[:180] for item in raw if str(item).strip()]
        return out[:5] or fallback

    category = text("category", FEATURE_CATEGORIES[(lane - 1) % len(FEATURE_CATEGORIES)]).lower()
    if category not in FEATURE_CATEGORIES:
        category = FEATURE_CATEGORIES[(lane - 1) % len(FEATURE_CATEGORIES)]
    accent = text("accent", "#375a7f")
    if not (accent.startswith("#") and len(accent) == 7):
        accent = "#375a7f"
    return {
        "id": f"feature-{lane:02d}",
        "ownerLane": f"lane-{lane:02d}",
        "title": text("title", f"Feature {lane:02d}"),
        "category": category,
        "metric": text("metric", f"lane {lane:02d} ready"),
        "accent": accent,
        "problem": text("problem", "Unspecified coordination problem."),
        "workflow": items("workflow", ["Receive input", "Validate output", "Report status"]),
        "acceptanceChecks": items("acceptanceChecks", ["Imports cleanly", "Renders content"]),
        "implementationNotes": text("implementationNotes", "No notes supplied."),
    }


def render_module(lane: int, payload: dict[str, Any]) -> str:
    feature = normalize_payload(lane, payload)
    data = json.dumps(feature, indent=2, ensure_ascii=False)
    return (
        f"export const feature = {data};\n\n"
        "export function renderFeature() {\n"
        "  const workflow = feature.workflow.map((item) => `<li>${item}</li>`).join('');\n"
        "  const checks = feature.acceptanceChecks.map((item) => `<li>${item}</li>`).join('');\n"
        "  return `<article class=\"feature-card\" style=\"--accent:${feature.accent}\">\n"
        "    <p class=\"eyebrow\">${feature.ownerLane} / ${feature.category}</p>\n"
        "    <h2>${feature.title}</h2>\n"
        "    <strong>${feature.metric}</strong>\n"
        "    <p>${feature.problem}</p>\n"
        "    <h3>Workflow</h3><ol>${workflow}</ol>\n"
        "    <h3>Acceptance</h3><ul>${checks}</ul>\n"
        "    <small>${feature.implementationNotes}</small>\n"
        "  </article>`;\n"
        "}\n"
    )


def write_feature(root: Path, spec: LaneSpec, module_text: str) -> None:
    expected_dir = (root / "product" / "features").resolve()
    target = spec.path.resolve()
    if target.parent != expected_dir:
        raise ValueError(f"lane target escaped features directory: {target}")
    target.write_text(module_text, encoding="utf-8")


def run_evaluator(root: Path) -> dict[str, Any]:
    proc = subprocess.run(
        ["node", str(root / "product" / "scripts" / "evaluate.mjs")],
        cwd=str(root / "product"),
        text=True,
        capture_output=True,
        check=False,
    )
    payload: dict[str, Any] = {"returncode": proc.returncode, "stdout": proc.stdout, "stderr": proc.stderr}
    try:
        parsed = json.loads(proc.stdout.strip() or "{}")
    except json.JSONDecodeError as exc:
        payload["parse_error"] = str(exc)
    else:
        if isinstance(parsed, dict):
            payload.update(parsed)
    return payload


def count_product_lines(root: Path) -> dict[str, int]:
    total = 0
    nonblank = 0
    for path in (root / "product").rglob("*"):
        if not path.is_file():
            continue
        lines = path.read_text(encoding="utf-8").splitlines()
        total += len(lines)
        nonblank += sum(1 for line in lines if line.strip())
    return {"total": total, "nonblank": nonblank}


def _spec_text(count: int) -> str:
    return (
        "# Native Swarm Product Benchmark\n\n"
        f"Build {count} independent feature modules for an agent-operations dashboard.\n"
        "Each lane owns exactly one `product/features/feature-NN.mjs` file. "
        "The host runner renders the final module and rejects path escape.\n"
    )


def _index_html() -> str:
    return (
        "<!doctype html><meta charset=\"utf-8\"><title>Native Swarm Product</title>"
        "<link rel=\"stylesheet\" href=\"./src/styles.css\"><main id=\"app\"></main>"
        "<script type=\"module\" src=\"./src/app.mjs\"></script>\n"
    )


def _app_js(count: int) -> str:
    imports = "\n".join(
        f"import {{ feature as f{i}, renderFeature as r{i} }} from '../features/feature-{i:02d}.mjs';"
        for i in range(1, count + 1)
    )
    rows = ",\n  ".join(f"{{ feature: f{i}, render: r{i} }}" for i in range(1, count + 1))
    return (
        f"{imports}\n\nconst modules = [\n  {rows}\n];\n"
        "document.querySelector('#app').innerHTML = `<section class=\"hero\"><h1>Agent Ops Deck</h1>"
        "<p>${modules.length} independently generated modules.</p></section>` + "
        "modules.map((item) => item.render()).join('');\n"
    )


def _styles_css() -> str:
    return (
        ":root{font-family:'Segoe UI',sans-serif;color:#17202a;background:#eef1e7}"
        "body{margin:0}.hero{padding:48px;background:#17202a;color:#f8f3e8}"
        "#app{display:grid;gap:18px}.feature-card{margin:0 24px;padding:24px;border-left:8px solid var(--accent);"
        "background:white;box-shadow:0 12px 30px #0001}.eyebrow{text-transform:uppercase;letter-spacing:.12em}"
        "h2{margin:.2rem 0}strong{color:var(--accent)}"
    )


def _evaluator_js(count: int) -> str:
    return f"""
const results = [];
for (let i = 1; i <= {count}; i += 1) {{
  const id = String(i).padStart(2, '0');
  try {{
    const mod = await import(`../features/feature-${{id}}.mjs?cache=${{Date.now()}}`);
    const html = mod.renderFeature();
    const feature = mod.feature || {{}};
    const ok = feature.id === `feature-${{id}}` &&
      feature.ownerLane === `lane-${{id}}` &&
      typeof html === 'string' &&
      html.includes(feature.title || '') &&
      Array.isArray(feature.workflow) &&
      feature.workflow.length >= 3;
    results.push({{ lane: i, ok, id: feature.id, ownerLane: feature.ownerLane }});
  }} catch (error) {{
    results.push({{ lane: i, ok: false, error: String(error && error.message || error) }});
  }}
}}
const passed = results.filter((row) => row.ok).length;
const failed = results.length - passed;
console.log(JSON.stringify({{ passed, failed, pass_rate: passed / results.length, results }}, null, 2));
process.exit(failed === 0 ? 0 : 1);
""".lstrip()
