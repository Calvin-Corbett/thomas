"""Standalone app door: open any command-center plugin as its own app.

``GET /app/{plugin_id}`` is the second door into a workspace module
(EXTENSION_STANDARD.md, "the standalone principle"). Through Thomas, a
module lives in the left nav with full chrome; through this route, the
module's surface IS the whole app and Thomas is just the engine
underneath. Desktop shortcuts generated by
``scripts/standalone_shortcut.py`` point here.

Failure pages are friendly HTML, not JSON — the person double-clicking
a desktop shortcut may never have opened Thomas itself.
"""

from __future__ import annotations

import html
import logging
from typing import Any

from aiohttp import web

from thomas.server.app_keys import APP_CONFIG
from thomas.server.desktop_plugins import get_installed_plugin

log = logging.getLogger(__name__)

_PAGE_TEMPLATE = """<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{title}</title>
  <style>
    body {{ margin: 0; min-height: 100vh; display: flex; align-items: center;
           justify-content: center; background: #14141f; color: #e8e6f0;
           font-family: "Segoe UI", system-ui, sans-serif; }}
    .card {{ max-width: 460px; padding: 36px 40px; background: #1c1c2b;
            border: 1px solid #32324a; border-radius: 14px; text-align: center; }}
    h1 {{ font-size: 19px; margin: 0 0 10px; }}
    p {{ font-size: 14px; line-height: 1.55; color: #9c9ab3; margin: 0 0 8px; }}
    .hint {{ font-size: 12.5px; color: #6f6d88; margin-top: 14px; }}
  </style>
</head>
<body>
  <div class="card">
    <h1>{heading}</h1>
    <p>{message}</p>
    <p class="hint">Powered by Thomas — this app runs on your local Thomas engine.</p>
  </div>
</body>
</html>"""


def _friendly_page(*, title: str, heading: str, message: str, status: int) -> web.Response:
    body = _PAGE_TEMPLATE.format(
        title=html.escape(title),
        heading=html.escape(heading),
        message=html.escape(message),
    )
    return web.Response(text=body, status=status, content_type="text/html")


def _surface_url(plugin: dict[str, Any]) -> str:
    """Surface URL from an installed record (normalized rows carry a flat
    surface_url; raw manifest-shaped dicts carry surface.entry_html)."""
    url = str(plugin.get("surface_url") or "").strip()
    if url:
        return url
    surface = plugin.get("surface") if isinstance(plugin.get("surface"), dict) else {}
    entry = str(surface.get("entry_html") or "").strip()
    plugin_id = str(plugin.get("plugin_id") or "").strip()
    return f"/plugins/{plugin_id}/{entry}" if plugin_id and entry else ""


def register_standalone_app_routes(
    app: web.Application,
    *,
    require_api_access,
) -> None:
    async def standalone_app(request: web.Request) -> web.Response:
        require_api_access(request)
        plugin_id = str(request.match_info.get("plugin_id") or "").strip()
        if not plugin_id:
            raise web.HTTPNotFound(text="plugin_id is required")
        config = app[APP_CONFIG]
        plugin = get_installed_plugin(config, plugin_id)
        display_name = str((plugin or {}).get("display_name") or plugin_id)
        if plugin is None:
            return _friendly_page(
                title="App not installed",
                heading=f"{display_name} isn't installed yet",
                message=(
                    "Open Thomas, go to the marketplace, and install "
                    f"“{display_name}”. Then this shortcut will open it directly."
                ),
                status=404,
            )
        if not plugin.get("enabled"):
            return _friendly_page(
                title="App is turned off",
                heading=f"{display_name} is currently disabled",
                message=(f"Open Thomas and enable “{display_name}” in the marketplace, then try this shortcut again."),
                status=403,
            )
        surface_url = _surface_url(plugin)
        if not surface_url:
            return _friendly_page(
                title="No app screen",
                heading=f"{display_name} has no standalone screen",
                message=(
                    "This module runs inside Thomas only. Open Thomas to use it — "
                    "only app modules (workspaces) open as their own window."
                ),
                status=404,
            )
        log.info("Standalone app launch: %s", plugin_id)
        raise web.HTTPFound(f"{surface_url}?standalone=1")

    app.router.add_get("/app/{plugin_id}", standalone_app)
